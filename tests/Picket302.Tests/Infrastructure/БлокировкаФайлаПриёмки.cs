using System.IO;

namespace Picket302.Tests.Infrastructure;

/// <summary>
/// Файловая блокировка COM-приёмки: межпроцессная сериализация
/// acceptance-сценариев, использующих общие ключи
/// <c>HKCU\Software\Classes</c> (регистрация и отзыв COM-сервера
/// конфликтуют между одновременными тестовыми процессами).
/// </summary>
/// <remarks>
/// <para>
/// Дефект прежней реализации: файл блокировки создавался
/// <c>FileMode.OpenOrCreate</c> и никогда не удалялся — поток
/// освобождал блокировку, но нулевой
/// <c>%TEMP%\Picket302.ComAcceptance.lock</c> оставался в %TEMP%
/// навсегда (после каждого прогона с COM-сценарием).
/// </para>
/// <para>
/// Исправление — <see cref="FileOptions.DeleteOnClose"/>: файл удаляется
/// ОС в момент закрытия последнего дескриптора. Все четыре контракта
/// выполняются конструктивно:
/// (1) сериализация — <see cref="FileShare.None"/> не даёт второму
/// процессу открыть файл, пока держим (sharing violation → ограниченное
/// ожидание в цикле захвата); DeleteOnClose не ослабляет проверку:
/// .NET форсирует только <c>FILE_SHARE_DELETE</c>, а запрашиваемый
/// <c>Read/Write</c> доступ всё равно запрещён режимом совместного
/// доступа владельца;
/// (2) удаление — ядро удаляет файл при закрытии дескриптора;
/// (3) аварийная смерть владельца — ОС закрывает дескриптор и файл
/// исчезает без дополнительных действий;
/// (4) устаревший файл от прежней реализации переживается следующим
/// захватом (<c>OpenOrCreate</c> открывает его как обычный файл) и
/// удаляется при закрытии нового владельца.
/// </para>
/// <para>
/// Класс internal: путь lock-файла — параметр, поэтому regression-тесты
/// проверяют реальную production-test-инфраструктуру на контролируемом
/// пути, не задевая общий lock других прогонов и production-профиль.
/// </para>
/// </remarks>
internal static class БлокировкаФайлаПриёмки
{
    /// <summary>Имя файла блокировки COM-приёмки в %TEMP%.</summary>
    internal const string ИмяФайла = "Picket302.ComAcceptance.lock";

    /// <summary>Полный путь блокировки по умолчанию (%TEMP%).</summary>
    internal static string ПутьПоУмолчанию() => Path.Combine(Path.GetTempPath(), ИмяФайла);

    /// <summary>
    /// Захватывает файл блокировки по явному пути: одновременный
    /// конкурент ждёт освобождения в пределах указанного времени, при
    /// исчерпании бюджета — fail-closed <see cref="IOException"/>.
    /// Поток открывается с <see cref="FileOptions.DeleteOnClose"/>:
    /// пока он открыт — файл существует и никому не выдаётся; при
    /// закрытии (штатном или аварийном) ОС удаляет файл.
    /// </summary>
    /// <param name="путь">Полный путь lock-файла.</param>
    /// <param name="ожидание">Полное время ожидания освобождения.</param>
    /// <returns>Открытый поток блокировки.</returns>
    internal static FileStream Захватить(string путь, TimeSpan ожидание)
    {
        var дедлайн = DateTime.UtcNow + ожидание;

        while (true)
        {
            try
            {
                // bufferSize: 1 — внутренняя буферизация не нужна: поток
                // используется только как держатель эксклюзивного
                // дескриптора, чтение/запись не выполняются.
                return new FileStream(
                    путь,
                    FileMode.OpenOrCreate,
                    FileAccess.ReadWrite,
                    FileShare.None,
                    bufferSize: 1,
                    options: FileOptions.DeleteOnClose);
            }
            catch (IOException)
            {
                if (DateTime.UtcNow >= дедлайн)
                {
                    throw new IOException(
                        "Блокировка COM-приёмки не освобождена за " +
                        $"{ожидание.TotalSeconds:0} секунд: " +
                        "параллельный тестовый прогон выполняет собственный COM-сценарий.");
                }

                Thread.Sleep(500);
            }
        }
    }
}
