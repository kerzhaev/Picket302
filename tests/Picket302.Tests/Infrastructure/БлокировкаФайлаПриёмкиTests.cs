using System.IO;
using Xunit;

namespace Picket302.Tests.Infrastructure;

/// <summary>
/// Контракт файловой блокировки COM-приёмки без COM-активации:
/// файл существует, пока дескриптор открыт; удаляется ОС при закрытии;
/// устаревший файл от прежней реализации (без DeleteOnClose)
/// поглощается новым владельцем и удаляется; конкурент получает
/// fail-closed отказ за ограниченное время, а после освобождения —
/// блокировку; повторный захват работает.
/// </summary>
/// <remarks>
/// Путь lock-файла — уникальный тестовый (guid) в %TEMP%: тест
/// проверяет реальную production-test-инфраструктуру
/// (internal-хелпер <see cref="БлокировкаФайлаПриёмки"/>, который
/// используется самим <c>AcceptanceScenarioTests</c>), не задевая
/// общий lock других прогонов и production-профиль. Отсутствие файла
/// после закрытия проверяется ограниченным опросом с дедлайном.
/// </remarks>
[Collection("ИнфраструктурнаяУборка")]
public sealed class БлокировкаФайлаПриёмкиTests
{
    /// <summary>Ограниченный опрос отсутствия файла: ядро удаляет
    /// DeleteOnClose-файл при закрытии дескриптора, но запись каталога
    /// может обновляться с задержкой — ожидание строго ограничено.</summary>
    private static bool ФайлОтсутствует(string путь, int секунд = 5)
    {
        var дедлайн = DateTime.UtcNow + TimeSpan.FromSeconds(секунд);

        while (DateTime.UtcNow < дедлайн)
        {
            if (!File.Exists(путь))
            {
                return true;
            }

            Thread.Sleep(100);
        }

        return !File.Exists(путь);
    }

    private static string ТестовыйПуть() => Path.Combine(
        Path.GetTempPath(),
        "Picket302.ComAcceptance.lock.test-" + Guid.NewGuid().ToString("N"));

    /// <summary>Пока дескриптор открыт — файл существует и никому не
    /// выдаётся; при закрытии ОС удаляет файл; повторный захват
    /// создаёт его заново и снова удаляет.</summary>
    [Fact]
    public void БлокировкаПриёмки_ФайлУдаляетсяПриЗакрытии_ИПовторныйЗахватРаботает()
    {
        var путь = ТестовыйПуть();

        try
        {
            using (var поток = БлокировкаФайлаПриёмки.Захватить(
                путь, TimeSpan.FromSeconds(15)))
            {
                Assert.True(File.Exists(путь),
                    "lock-файл должен существовать, пока дескриптор открыт");
            }

            Assert.True(ФайлОтсутствует(путь),
                "lock-файл должен быть удалён ОС после закрытия дескриптора (DeleteOnClose)");

            // Повторный захват после освобождения: файл создаётся заново.
            using (var поток = БлокировкаФайлаПриёмки.Захватить(
                путь, TimeSpan.FromSeconds(15)))
            {
                Assert.True(File.Exists(путь),
                    "повторный захват должен создать lock-файл заново");
            }

            Assert.True(ФайлОтсутствует(путь),
                "lock-файл должен быть удалён и после повторного закрытия");
        }
        finally
        {
            // Постусловие теста: артефакт не должен пережить прогон
            // даже при неожиданном поведении ФС. Наш собственный
            // уникальный файл — чужие TEMP-артефакты не трогаем.
            try { File.Delete(путь); } catch (IOException) { }
        }
    }

    /// <summary>Устаревший lock-файл, оставленный прежней реализацией
    /// (OpenOrCreate без DeleteOnClose, дескриптор давно закрыт),
    /// переживается следующим захватом и исчезает после закрытия
    /// нового владельца — миграция старых артефактов не требует
    /// ручной чистки %TEMP%.</summary>
    [Fact]
    public void БлокировкаПриёмки_УстаревшийФайлПоглощаетсяИУдаляется()
    {
        var путь = ТестовыйПуть();

        try
        {
            // Имитация артефакта прежней реализации: обычный файл с
            // содержимым, дескриптор закрыт.
            File.WriteAllText(путь, "stale-lock-from-old-implementation");
            Assert.True(File.Exists(путь));

            using (var поток = БлокировкаФайлаПриёмки.Захватить(
                путь, TimeSpan.FromSeconds(15)))
            {
                Assert.True(File.Exists(путь),
                    "устаревший lock-файл должен открываться как обычный файл (OpenOrCreate)");
            }

            Assert.True(ФайлОтсутствует(путь),
                "устаревший lock-файл должен быть удалён после закрытия нового владельца");
        }
        finally
        {
            try { File.Delete(путь); } catch (IOException) { }
        }
    }

    /// <summary>Второй конкурент не получает блокировку, пока дескриптор
    /// открыт (fail-closed IOException за ограниченный бюджет), а после
    /// освобождения получает её: DeleteOnClose не ослабляет
    /// FileShare.None — сериализация COM-приёмки сохранена.</summary>
    /// <remarks>
    /// Эксклюзивность проверяется вторым дескриптором в том же процессе:
    /// проверка совместного доступа выполняется ядром одинаково для
    /// любых процессов, поэтому in-process дескриптор доказывает те же
    /// kernel-гарантии, что и межпроцессный конфликт.
    /// </remarks>
    [Fact]
    public void БлокировкаПриёмки_КонкурентЗапрещёнПокаДержим_ИДопущенПослеОсвобождения()
    {
        var путь = ТестовыйПуть();

        try
        {
            var поток = БлокировкаФайлаПриёмки.Захватить(путь, TimeSpan.FromSeconds(15));

            try
            {
                // Бюджет мал и детерминирован: конкурент обязан
                // отказаться с диагностированным отказом.
                var отказ = Assert.Throws<IOException>(() =>
                    БлокировкаФайлаПриёмки.Захватить(путь, TimeSpan.FromSeconds(1)));

                Assert.Contains("не освобождена", отказ.Message);
            }
            finally
            {
                поток.Dispose();
            }

            // После освобождения блокировка выдаётся немедленно.
            using (var повтор = БлокировкаФайлаПриёмки.Захватить(
                путь, TimeSpan.FromSeconds(15)))
            {
                Assert.True(File.Exists(путь),
                    "после освобождения конкурент должен получить блокировку");
            }

            Assert.True(ФайлОтсутствует(путь));
        }
        finally
        {
            try { File.Delete(путь); } catch (IOException) { }
        }
    }
}
