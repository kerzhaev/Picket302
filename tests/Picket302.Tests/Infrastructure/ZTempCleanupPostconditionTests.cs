using Xunit;

namespace Picket302.Tests.Infrastructure;

/// <summary>
/// Дополнительная (не единственная) проверка чистоты reparse-тестов:
/// каталоги <c>%TEMP%\P302GuardTest_*</c> не остаются.
/// </summary>
/// <remarks>
/// Гарантированная проверка после ВСЕЙ коллекции — teardown фикстуры
/// <see cref="ПостусловиеЧистотыGuard"/>; этот тест — дополнительная
/// точка контроля внутри прогона. Имя класса с префиксом «Z» держит
/// проверку после гард-тестов в алфавитном порядке xUnit, но порядок по
/// имени классов НЕ является гарантией жизненного цикла — поэтому
/// основная проверка вынесена в фикстуру.
/// </remarks>
[Collection("ИнфраструктурнаяУборка")]
public sealed class ZTempCleanupPostconditionTests
{
    /// <summary>
    /// Фикстура постусловия: внедряется явно, чтобы xUnit гарантированно
    /// создал её и выполнил teardown после коллекции.
    /// </summary>
    private readonly ПостусловиеЧистотыGuard _постусловие;

    /// <summary>Создаёт тест с фикстурой постусловия коллекции.</summary>
    /// <param name="постусловие">Фикстура постусловия коллекции.</param>
    public ZTempCleanupPostconditionTests(ПостусловиеЧистотыGuard постусловие)
    {
        _постусловие = постусловие;
    }

    /// <summary>
    /// После reparse-тестов гарда не остаётся ни одного каталога
    /// <c>P302GuardTest_*</c> в %TEMP% (проверка под межпроцессной
    /// блокировкой).
    /// </summary>
    [Fact]
    public void Прогон_ГардаНеОставляетКаталоговP302GuardTest()
    {
        // Та же проверка, что и в teardown фикстуры: полный список
        // остатков в диагностике при нарушении.
        ПостусловиеЧистотыGuard.ПроверитьЧистоту();
    }
}
