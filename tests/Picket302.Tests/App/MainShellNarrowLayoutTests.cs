using System.Windows.Forms;
using Picket302.App;
using Xunit;

namespace Picket302.Tests.App;

/// <summary>
/// Контракт главного окна на узкой ширине (аудит 2026-11-08):
/// <list type="bullet">
/// <item>группа «Вид логотипа» растёт по содержимому: подписи
/// «С логотипом»/«Без логотипа»/«Отправителя»/«Получателя» переносятся, а
/// не обрезаются; превью не обрезает заголовок;</item>
/// <item>полоса кнопок «Кому» разделена на первичные действия
/// (Добавить/Изменить/Удалить/Печать текущего конверта/Предпросмотр и
/// печать) и дополнительные (Открыть список в Excel/Сохранить вид
/// таблицы/Вид таблиц…) — перенос предсказуем, кнопка не уходит «сама» на
/// третий ряд;</item>
/// <item>при размерах окна 1000×700 и 1280×720 все пять обязательных кнопок
/// печатающих действий остаются в клиентской области, AccessibleName
/// сохранены;</item>
/// <item>политика адреса получателя (вариант A): сообщение о формировании
/// отправлений перечисляет получателей без основного адреса поимённо, а не
/// молча.</item>
/// </list>
/// Проверяются свойства компоновки иерархии; COM, печать и профиль не
/// используются.
/// </summary>
[Collection("WinFormsПрофиль")]
public sealed class MainShellNarrowLayoutTests
{
    private static IEnumerable<Control> Обойти(Control контейнер)
    {
        foreach (Control элемент in контейнер.Controls)
        {
            yield return элемент;

            foreach (var вложенный in Обойти(элемент))
            {
                yield return вложенный;
            }
        }
    }

    private static IReadOnlyList<FlowLayoutPanel> ПолосыКнопокКому(MainShell окно)
    {
        var группа = Обойти(окно)
            .OfType<GroupBox>()
            .Single(блок => блок.Text == "Кому");

        return Обойти(группа)
            .OfType<FlowLayoutPanel>()
            .Where(поток => поток.Controls.OfType<Button>().Any())
            .ToList();
    }

    // ------------------------------------------------------------------
    // Полоса кнопок «Кому»: первичные и дополнительные действия.
    // ------------------------------------------------------------------

    /// <summary>
    /// Действия получателя разделены на две полосы: первичные (печать и
    /// правка записей) и дополнительные (выгрузка и оформление таблицы).
    /// Обе полосы растут по содержимому.
    /// </summary>
    [Fact]
    public void ГлавныйЭкран_КнопкиКому_РазделеныНаПервичныеИДополнительные()
    {
        using var окно = new MainShell();
        окно.CreateControl();
        окно.PerformLayout();

        var полосы = ПолосыКнопокКому(окно);

        Assert.Equal(2, полосы.Count);

        var первичная = полосы.Single(поток => поток.Controls.OfType<Button>().Any(кнопка => кнопка.Text == "Добавить"));
        var дополнительная = полосы.Single(поток => поток.Controls.OfType<Button>().Any(кнопка => кнопка.Text == "Открыть список в Excel"));

        Assert.Equal(
            new[] { "Добавить", "Изменить", "Удалить", "Печать текущего конверта", "Предпросмотр и печать" },
            первичная.Controls.OfType<Button>().Select(кнопка => кнопка.Text).ToArray());

        Assert.Equal(
            new[] { "Открыть список в Excel", "Сохранить вид таблицы", "Вид таблиц…" },
            дополнительная.Controls.OfType<Button>().Select(кнопка => кнопка.Text).ToArray());

        Assert.True(первичная.AutoSize, "Первичная полоса кнопок должна расти по содержимому.");
        Assert.True(дополнительная.AutoSize, "Полоса дополнительных действий должна расти по содержимому.");
    }

    /// <summary>
    /// При размере окна 1000×700 все обязательные кнопки остаются в
    /// клиентской области: «Печать текущего конверта», «Предпросмотр и
    /// печать», «Открыть список в Excel», «Сохранить вид таблицы»,
    /// «Вид таблиц…»; AccessibleName сохранены.
    /// </summary>
    [Fact]
    public void ГлавныйЭкран_1000x700_КнопкиДействий_ВКлиентскойОбласти()
    {
        ПроверитьКнопкиНаРазмере(1000, 700);
    }

    /// <summary>
    /// Тот же контракт при 1280×720.
    /// </summary>
    [Fact]
    public void ГлавныйЭкран_1280x720_КнопкиДействий_ВКлиентскойОбласти()
    {
        ПроверитьКнопкиНаРазмере(1280, 720);
    }

    private static void ПроверитьКнопкиНаРазмере(int ширина, int высота)
    {
        using var окно = new MainShell();
        окно.CreateControl();
        окно.ClientSize = new Size(ширина, высота);
        окно.PerformLayout();

        var обязательные = new[]
        {
            "Печать текущего конверта",
            "Предпросмотр и печать",
            "Открыть список в Excel",
            "Сохранить вид таблицы",
            "Вид таблиц…",
        };

        var кнопки = Обойти(окно).OfType<Button>().ToList();

        foreach (var имя in обязательные)
        {
            var кнопка = кнопки.Single(элемент => элемент.Text == имя);

            Assert.True(
                окно.ClientRectangle.Contains(кнопка.Bounds),
                $"Кнопка «{имя}» вне клиентской области {окно.ClientRectangle}: {кнопка.Bounds}.");
            Assert.False(string.IsNullOrWhiteSpace(кнопка.AccessibleName), $"Кнопка «{имя}» должна сохранять AccessibleName.");
        }
    }

    // ------------------------------------------------------------------
    // Колонка «Вид логотипа»: перенос вместо обрезания.
    // ------------------------------------------------------------------

    /// <summary>
    /// Группа «Вид логотипа» растёт по содержимому, ряды переключателей
    /// переносятся (а не обрезаются), и при 1000×700 подписи «С логотипом»,
    /// «Без логотипа», «Отправителя», «Получателя» остаются в клиентской
    /// области окна.
    /// </summary>
    [Fact]
    public void ГлавныйЭкран_1000x700_ПодписиЛоготипа_ВидныБезОбрезания()
    {
        using var окно = new MainShell();
        окно.CreateControl();
        окно.ClientSize = new Size(1000, 700);
        окно.PerformLayout();

        var группа = Обойти(окно).OfType<GroupBox>().Single(блок => блок.Text == "Вид логотипа");

        Assert.True(группа.AutoSize, "Группа «Вид логотипа» обязана расти по содержимому.");

        var ряды = Обойти(группа).OfType<FlowLayoutPanel>().ToList();

        Assert.All(ряды, ряд => Assert.True(ряд.WrapContents, "Ряды переключателей обязаны переноситься, а не обрезаться."));

        foreach (var подпись in new[] { "С логотипом", "Без логотипа", "Отправителя", "Получателя" })
        {
            var переключатель = ряды
                .SelectMany(ряд => ряд.Controls.OfType<RadioButton>())
                .Single(элемент => элемент.Text == подпись);

            Assert.True(
                окно.ClientRectangle.Contains(переключатель.Bounds),
                $"Переключатель «{подпись}» вне клиентской области {окно.ClientRectangle}: {переключатель.Bounds}.");
        }

        // Превью: контейнер не уже текста заголовка — «Превью конверта C5»
        // не обрезается.
        var превью = Обойти(группа).OfType<Panel>()
            .Where(панель => панель.Dock == DockStyle.Right)
            .Single();

        Assert.True(превью.Width >= 140, "Контейнер превью обязан вмещать заголовок «Превью конверта C5».");
    }

    // ------------------------------------------------------------------
    // Политика адреса получателя (вариант A).
    // ------------------------------------------------------------------

    /// <summary>
    /// Без пропусков сообщение называет только число отправлений — как
    /// прежде.
    /// </summary>
    [Fact]
    public void ТекстФормирования_БезПропусков_НазываетЧисло()
    {
        var текст = MainShell.ТекстФормированияОтправлений(2, Array.Empty<string>());

        Assert.Contains("Отправлений сформировано: 2.", текст, StringComparison.Ordinal);
        Assert.DoesNotContain("Пропущены", текст, StringComparison.Ordinal);
    }

    /// <summary>
    /// Получатели без основного адреса перечисляются поимённо с подсказкой:
    /// пропуск не молчит (политика адреса получателя, вариант A).
    /// </summary>
    [Fact]
    public void ТекстФормирования_ПеречисляетПропущенныхБезАдреса()
    {
        var текст = MainShell.ТекстФормированияОтправлений(
            1,
            new[] { "Иванов И.И.", "ООО «Ромашка»" });

        Assert.Contains("Отправлений сформировано: 1.", текст, StringComparison.Ordinal);
        Assert.Contains("Пропущены без основного адреса (2)", текст, StringComparison.Ordinal);
        Assert.Contains("Иванов И.И.", текст, StringComparison.Ordinal);
        Assert.Contains("ООО «Ромашка»", текст, StringComparison.Ordinal);
        Assert.Contains("Заполните адрес в карточке контрагента", текст, StringComparison.Ordinal);
    }
}
