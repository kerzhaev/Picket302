    [Fact]
    public void ПерестроениеПослеИзмененияПорядка_ГруппыИдутПоНовомуПорядку()
    {
        var строки = new[]
        {
            ("Гостиницы", "Зубрёнок"),
            ("Клиенты", "Артис"),
        };
        using var таблица = СоздатьТаблицу(строки);
        using var контроллер = new RowGroupingController();
        контроллер.Подключить(таблица);
        контроллер.Применить("Группа");

        // Сортировка/поиск переворачивает порядок строк адресной книги.
        var последняя = таблица.Rows[3];
        таблица.Rows.Remove(последняя);
        таблица.Rows.Insert(0, 1);
        таблица.Rows[0].Tag = последняя.Tag;
        таблица.Rows[0].Cells[0].Value = "Клиенты";
        таблица.Rows[0].Cells[1].Value = "Артис";

        контроллер.Перестроить();

        Assert.Equal(
        [
            "− Клиенты (1)",
            "− Гостиницы (1)",
        ], контроллер.НадписиЗаголовков());
    }

    [Fact]
    public void ВыделениеСохраняетсяПриПерестроенииПоТегамЗаписей()
    {
        var строки = new[]
        {
            ("Гостиницы", "Зубрёнок"),
            ("Клиенты", "Артис"),
            ("Гостиницы", "Юбилейная"),
        };
        using var таблица = СоздатьТаблицу(строки);
        using var контроллер = new RowGroupingController();
        контроллер.Подключить(таблица);
        контроллер.Применить("Группа");

        таблица.Rows[4].Selected = true; // Артис (Клиенты): 0=заголовок Г, 1=Зубрёнок, 2=Юбилейная, 3=заголовок К

        контроллер.Перестроить();

        var выбранная = таблица.Rows
            .Cast<DataGridViewRow>()
            .Single(строка => строка.Selected);
        Assert.Equal(2L, выбранная.Tag);
    }

    /// <summary>
    /// Навигация поиска при активной группировке: соответствие строка ↔
    /// список через тег-идентификатор, а не позицию (ревью S07 F1):
    /// заголовки групп и блочный перепорядок не смещают индексы.
    /// </summary>
    [Fact]
    public void СписочныйИндекс_ПриГруппировкеСсылаетсяНаТегаНеНаПозиции()
    {
        // Исходный порядок списка: 1(Гостиницы), 2(Клиенты), 3(Гостиницы).
        var строки = new[]
        {
            ("Гостиницы", "Зубрёнок"),
            ("Клиенты", "Артис"),
            ("Гостиницы", "Юбилейная"),
        };
        using var таблица = СоздатьТаблицу(строки);
        using var контроллер = new RowGroupingController();
        контроллер.Подключить(таблица);
        контроллер.Применить("Группа");

        // Грид после группировки: H,1,3,H,2 — выделена строка Ид=3 (грид-индекс 2).
        таблица.Rows[2].Selected = true;

        long[] идентификаторы = [1, 2, 3];

        // Прямое различие пространств: грид-строка 1 (Ид=1, после
        // заголовка) — списочный индекс 0; старая индексная реализация
        // вернула бы 1 (ревью S07 F-R2-3).
        Assert.Equal(0, RowGroupingController.СписочныйИндекс(таблица.Rows[1], идентификаторы));
        Assert.Equal(2, RowGroupingController.СписочныйИндекс(таблица.Rows[2], идентификаторы));
        // Строка-заголовок не отображается на список.
        Assert.Equal(-1, RowGroupingController.СписочныйИндекс(таблица.Rows[0], идентификаторы));
        // Обратный маппинг: Ид=2 — это грид-строка 4, а не 1.
        Assert.Equal(4, RowGroupingController.СтрокаПоИдентификатору(таблица, 2)!.Index);
        Assert.Null(RowGroupingController.СтрокаПоИдентификатору(таблица, 99));
    }

    /// <summary>
    /// Свёрнутость группы переживает перестроение (ревью S07 F4).
