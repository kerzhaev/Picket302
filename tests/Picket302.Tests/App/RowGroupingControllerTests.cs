    /// <summary>
    /// Снятие группировки возвращает исходный (до-блочный) порядок строк
    /// (ревью S07 F5): фикстура с перемешанными группами.
    /// </summary>
    [Fact]
    public void СнятиеГруппировки_ВосстанавливаетИсходныйПорядокСтрок()
    {
        var строки = new[]
        {
            ("Гостиницы", "Зубрёнок"),   // Ид=1
            ("Клиенты", "Артис"),        // Ид=2
            ("Гостиницы", "Юбилейная"),  // Ид=3
        };
        using var таблица = СоздатьТаблицу(строки);
        using var контроллер = new RowGroupingController();
        контроллер.Подключить(таблица);
        контроллер.Применить("Группа");

        // Блочный перепорядок: Гостиницы(1,3), Клиенты(2).
        Assert.Equal("Юбилейная", таблица.Rows[2].Cells[1].Value);

        контроллер.Применить(null);

        Assert.Equal(0, контроллер.КоличествоЗаголовков);
        Assert.Equal(1L, таблица.Rows[0].Tag);
        Assert.Equal(2L, таблица.Rows[1].Tag);
        Assert.Equal(3L, таблица.Rows[2].Tag);
    }

    /// <summary>
    /// Перезагрузка набора строк сбрасывает снимок порядка: снятие
    /// группировки восстанавливает порядок НОВОЙ загрузки, а не устаревшей
    /// (ревью S07 F-R2-2).
    /// </summary>
    [Fact]
    public void ПерезагрузкаСтрок_СбрасываетСнимокПорядка()
    {
        using var таблица = СоздатьТаблицу([("Гостиницы", "Старая"), ("Клиенты", "Старая2")]);
        using var контроллер = new RowGroupingController();
        контроллер.Подключить(таблица);
        контроллер.Применить("Группа");

        // «Перезагрузка»: строки заменены в другом порядке и составе.
        таблица.Rows.Clear();
        var первая = таблица.Rows.Add("Клиенты", "Новая-A");
        таблица.Rows[первая].Tag = 10L;
        var вторая = таблица.Rows.Add("Гостиницы", "Новая-B");
        таблица.Rows[вторая].Tag = 11L;
        контроллер.СброситьСнимокПорядка();
        контроллер.Перестроить();

        контроллер.Применить(null);

        Assert.Equal(0, контроллер.КоличествоЗаголовков);
        Assert.Equal(10L, таблица.Rows[0].Tag);
        Assert.Equal(11L, таблица.Rows[1].Tag);
    }

    private static DataGridView СоздатьТаблицу((string Группа, string Имя)[] строки)
    {
        var таблица = new DataGridView
        {
            ColumnCount = 2,
            RowHeadersVisible = false,
            AllowUserToAddRows = false,
        };
        таблица.Columns[0].Name = "Группа";
        таблица.Columns[1].Name = "Получатель";

        for (var индекс = 0; индекс < строки.Length; индекс++)
        {
            var номер = таблица.Rows.Add(строки[индекс].Группа, строки[индекс].Имя);
            таблица.Rows[номер].Tag = (long)индекс + 1;
        }

        return таблица;
    }
