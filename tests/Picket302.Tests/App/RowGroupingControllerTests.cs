using System.Windows.Forms;
using Picket302.App.UI.Components;
using Xunit;

namespace Picket302.Tests.App;

/// <summary>
/// Контракт группировки строк адресной книги сворачиваемыми заголовками
/// (ТЗ §8.1, функция 10: «Группировка строк в списке, настройка и снятие
/// группировки»). Тесты не зависят от порядка запуска: каждый создаёт
/// собственную таблицу.
/// </summary>
[Collection("WinFormsПрофиль")]
public sealed class RowGroupingControllerTests
{
    [Fact]
    public void ПустаяТаблица_ГруппировкаНеДобавляетЗаголовков()
    {
        using var таблица = СоздатьТаблицу([]);
        using var контроллер = new RowGroupingController();
        контроллер.Подключить(таблица);

        контроллер.Применить("Группа");

        Assert.Equal(0, контроллер.КоличествоЗаголовков);
        Assert.Equal(0, таблица.Rows.Count);
    }

    [Fact]
    public void Группировка_ВставляетЗаголовкиСоСчётчикамиВПорядкеСтрок()
    {
        var строки = new[]
        {
            ("Гостиницы", "Зубрёнок"),
            ("Клиенты", "Артис"),
            ("Гостиницы", "Юбилейная"),
        };
        using var таблица = СоздатьТаблицу(строки);
        using var контроллер = new RowGroupingController();
        контроллер.Подключить(таблица);

        контроллер.Применить("Группа");

        Assert.Equal(2, контроллер.КоличествоЗаголовков);
        Assert.Equal(
        [
            "− Гостиницы (2)",
            "− Клиенты (1)",
        ], контроллер.НадписиЗаголовков());
        // Заголовок стоит перед первым вхождением группы.
        Assert.Equal("− Гостиницы (2)", таблица.Rows[0].Cells[0].Value);
        Assert.Equal("Зубрёнок", таблица.Rows[1].Cells[1].Value);
        Assert.Equal("Юбилейная", таблица.Rows[2].Cells[1].Value);
        Assert.Equal("− Клиенты (1)", таблица.Rows[3].Cells[0].Value);
        Assert.Equal("Артис", таблица.Rows[4].Cells[1].Value);
    }

    [Fact]
    public void ПустойКлючГруппы_ОбозначаетсяКакБезГруппы()
    {
        var строки = new[] { ("", "Один"), ("Гостиницы", "Два") };
        using var таблица = СоздатьТаблицу(строки);
        using var контроллер = new RowGroupingController();
        контроллер.Подключить(таблица);

        контроллер.Применить("Группа");

        Assert.Equal("− (без группы) (1)", контроллер.НадписиЗаголовков()[0]);
        Assert.Equal("− Гостиницы (1)", контроллер.НадписиЗаголовков()[1]);
    }

    [Fact]
    public void Сворачивание_СкрываетСтрокиГруппыИМеняетНадпись()
    {
        var строки = new[]
        {
            ("Гостиницы", "Зубрёнок"),
            ("Клиенты", "Артис"),
        };
        using var таблица = СоздатьТаблицу(строки);
        using var контроллер = new RowGroupingController();
        контроллер.Подключить(таблица);
        контроллер.Применить("Группа");

        контроллер.ПереключитьСвораченность(таблица.Rows[0]);

        Assert.Equal("+ Гостиницы (1)", таблица.Rows[0].Cells[0].Value);
        Assert.False(таблица.Rows[1].Visible);
        Assert.True(таблица.Rows[3].Visible);

        контроллер.ПереключитьСвораченность(таблица.Rows[0]);

        Assert.Equal("− Гостиницы (1)", таблица.Rows[0].Cells[0].Value);
        Assert.True(таблица.Rows[1].Visible);
    }

    [Fact]
    public void СнятиеГруппировки_УбираетЗаголовкиИВозвращаетВсеСтроки()
    {
        var строки = new[]
        {
            ("Гостиницы", "Зубрёнок"),
            ("Клиенты", "Артис"),
        };
        using var таблица = СоздатьТаблицу(строки);
        using var контроллер = new RowGroupingController();
        контроллер.Подключить(таблица);
        контроллер.Применить("Группа");
        контроллер.ПереключитьСвораченность(таблица.Rows[0]);

        контроллер.Применить(null);

        Assert.Null(контроллер.КолонкаГруппировки);
        Assert.Equal(0, контроллер.КоличествоЗаголовков);
        Assert.Equal(2, таблица.Rows.Count);
        Assert.All(таблица.Rows.Cast<DataGridViewRow>(), строка => Assert.True(строка.Visible));
    }

    [Fact]
    public void ПерестроениеПослеИзмененияПорядка_ГруппыИдутПоНовомуПорядку()
    {
        var строки = new[]
        {
            ("Гостиницы", "Зубрёнок"),
            ("Клиенты", "Артис"),
        };
        using var таблица = СоздатьТаблицу(строки);
        using var контроллер = new RowGroupingController();
        контроллер.Подключить(таблица);
        контроллер.Применить("Группа");

        // Сортировка/поиск переворачивает порядок строк адресной книги.
        var последняя = таблица.Rows[3];
        таблица.Rows.Remove(последняя);
        таблица.Rows.Insert(0, 1);
        таблица.Rows[0].Tag = последняя.Tag;
        таблица.Rows[0].Cells[0].Value = "Клиенты";
        таблица.Rows[0].Cells[1].Value = "Артис";

        контроллер.Перестроить();

        Assert.Equal(
        [
            "− Клиенты (1)",
            "− Гостиницы (1)",
        ], контроллер.НадписиЗаголовков());
    }

    [Fact]
    public void ВыделениеСохраняетсяПриПерестроенииПоТегамЗаписей()
    {
        var строки = new[]
        {
            ("Гостиницы", "Зубрёнок"),
            ("Клиенты", "Артис"),
            ("Гостиницы", "Юбилейная"),
        };
        using var таблица = СоздатьТаблицу(строки);
        using var контроллер = new RowGroupingController();
        контроллер.Подключить(таблица);
        контроллер.Применить("Группа");

        таблица.Rows[4].Selected = true; // Артис (Клиенты): 0=заголовок Г, 1=Зубрёнок, 2=Юбилейная, 3=заголовок К

        контроллер.Перестроить();

        var выбранная = таблица.Rows
            .Cast<DataGridViewRow>()
            .Single(строка => строка.Selected);
        Assert.Equal(2L, выбранная.Tag);
    }

    private static DataGridView СоздатьТаблицу((string Группа, string Имя)[] строки)
    {
        var таблица = new DataGridView
        {
            ColumnCount = 2,
            RowHeadersVisible = false,
            AllowUserToAddRows = false,
        };
        таблица.Columns[0].Name = "Группа";
        таблица.Columns[1].Name = "Получатель";

        for (var индекс = 0; индекс < строки.Length; индекс++)
        {
            var номер = таблица.Rows.Add(строки[индекс].Группа, строки[индекс].Имя);
            таблица.Rows[номер].Tag = (long)индекс + 1;
        }

        return таблица;
    }
}
