using Xunit;

namespace Picket302.Tests.App;

/// <summary>
/// Контракт компоновки карточки контрагента (редизайн 2026-11-08):
/// конфликт DockStyle.Top редакторов адреса и ручных Location устранён —
/// три адресных блока в адаптивной сетке, не пересекаются и не выходят за
/// границы вкладки; вкладка «Реквизиты» прокручивается; подписи колонок
/// реквизитов не обрезаются и не переносятся; пользовательские поля реально
/// доступны (заголовок, сетка, строка добавления, тег Custom_…); кнопки
/// «Сохранить»/«Отмена» закреплены на форме. Проверяются свойства
/// компоновки иерархии, а не пиксельные координаты; COM, реестр, принтер
/// и физическая печать не используются.
/// </summary>
/// <remarks>
/// Форма кратковременно показывается: без показа фиксированный диалог не
/// выполняет полную раскладку (TabControl остаётся в минимальном размере),
/// и геометрические проверки были бы проверкой «ничего». Коллекция
/// WinFormsПрофиль сериализует показ форм между тестами.
/// </remarks>
[Collection("WinFormsПрофиль")]
public sealed class FormCounterpartyLayoutTests
{
    private static IEnumerable<Control> Обойти(Control контейнер)
    {
        foreach (Control элемент in контейнер.Controls)
        {
            yield return элемент;

            foreach (var вложенный in Обойти(элемент))
            {
                yield return вложенный;
            }
        }
    }

    /// <summary>
    /// Показывает карточку и выполняет полную раскладку; вызов закрывает
    /// форму возвратом через using.
    /// </summary>
    private static FormCounterpartyEdit ПоказатьКарточку()
    {
        var форма = new FormCounterpartyEdit
        {
            StartPosition = FormStartPosition.Manual,
        };

        форма.Show();
        форма.PerformLayout();
        System.Windows.Forms.Application.DoEvents();

        return форма;
    }

    /// <summary>
    /// Границы контрола в координатах произвольного предка (не только
    /// формы) суммированием смещений по цепочке родителей.
    /// </summary>
    private static Rectangle ГраницыВ(Control контрол, Control предок)
    {
        var x = контрол.Left;
        var y = контрол.Top;

        for (var родитель = контрол.Parent; родитель is not null && !ReferenceEquals(родитель, предок); родитель = родитель.Parent)
        {
            x += родитель.Left;
            y += родитель.Top;
        }

        return new Rectangle(x, y, контрол.Width, контрол.Height);
    }

    // ------------------------------------------------------------------
    // Адресные блоки: сетка вместо конфликта Dock/Location.
    // ------------------------------------------------------------------

    /// <summary>
    /// Три редактора адреса лежат в одной адаптивной сетке: блоки не
    /// пересекаются и по горизонтали не выходят за клиентскую область
    /// вкладки (runtime-дефект 2026-11-08: блоки уходили до y≈927 и
    /// перекрывали панель пользовательских полей).
    /// </summary>
    [Fact]
    public void Карточка_ТриАдресныхБлока_НеПересекаютсяИВГраницах()
    {
        using var форма = ПоказатьКарточку();

        var редакторы = Обойти(форма).OfType<AddressEditor>().ToList();

        Assert.Equal(3, редакторы.Count);

        var контейнеры = редакторы.Select(редактор => редактор.Parent).Distinct().ToList();

        Assert.Single(контейнеры); // все три блока — в одной адаптивной сетке

        var вкладка = форма.СтраницаРеквизитов;

        for (var первый = 0; первый < редакторы.Count; первый++)
        {
            var границыПервого = ГраницыВ(редакторы[первый], вкладка);

            Assert.True(
                границыПервого.Right <= вкладка.ClientSize.Width,
                $"Адресный блок выходит по горизонтали за вкладку: {границыПервого} при ширине {вкладка.ClientSize.Width}.");

            for (var второй = первый + 1; второй < редакторы.Count; второй++)
            {
                var границыВторого = ГраницыВ(редакторы[второй], вкладка);

                Assert.False(
                    границыПервого.IntersectsWith(границыВторого),
                    $"Адресные блоки пересекаются: {границыПервого} ∩ {границыВторого}.");
            }
        }
    }

    /// <summary>
    /// Ни один адресный блок не выходит за границы вкладки «Реквизиты»:
    /// контент вкладки выше клиентской области достижим прокруткой, а не
    /// обрезается, и каждый видимый контрол лежит внутри прокручиваемого
    /// контента.
    /// </summary>
    [Fact]
    public void Карточка_ВкладкаРеквизитов_ПрокручиваетсяБезОбрезания()
    {
        using var форма = ПоказатьКарточку();

        var прокрутка = Обойти(форма.СтраницаРеквизитов)
            .OfType<ScrollableControl>()
            .Single(панель => панель.AutoScroll);

        // Контент выше клиентской области — прокрутка обязана его открывать:
        // либо AutoScrollMinSize, либо фактическая высота контента больше
        // видимой высоты.
        var контентВыше = прокрутка.AutoScrollMinSize.Height > прокрутка.ClientSize.Height
            || прокрутка.DisplayRectangle.Height > прокрутка.ClientSize.Height;

        Assert.True(
            контентВыше,
            $"Контент вкладки обязан требовать прокрутки: AutoScrollMinSize={прокрутка.AutoScrollMinSize}, DisplayRectangle={прокрутка.DisplayRectangle}, ClientSize={прокрутка.ClientSize}.");

        // Достижимая высота контента: максимум заявленного минимального
        // размера прокрутки и фактической нижней границы дочерних контролов
        // хоста — в AutoScroll-контейнере именно дочерние контролы задают
        // диапазон прокрутки.
        var достижимаяВысота = Math.Max(
            прокрутка.AutoScrollMinSize.Height,
            прокрутка.Controls.Cast<Control>().Max(дочерний => дочерний.Bottom));

        var переполнения = new List<string>();

        // Контейнеры переработанной вкладки (редизайн 2026-11-08):
        // вертикальная сетка и её прямые строки. Внутренности
        // AddressEditor (строки 22 px против минимальной высоты TextBox)
        // — отдельный компонент со своими проверками и вне области
        // этого контракта.
        var вертикаль = прокрутка.Controls.Cast<Control>().Single(контрол => контрол is TableLayoutPanel);
        var контейнерыВкладки = new List<Control> { вертикаль };
        контейнерыВкладки.AddRange(вертикаль.Controls.Cast<Control>());

        foreach (var контрол in Обойти(прокрутка))
        {
            if (!контрол.Visible)
            {
                continue;
            }

            // Прямые дети прокручиваемого хоста задают диапазон прокрутки
            // и проверяются по достижимой высоте, а не по клиентской.
            if (ReferenceEquals(контрол.Parent, прокрутка))
            {
                var границы = ГраницыВ(контрол, прокрутка);

                if (границы.Bottom > достижимаяВысота)
                {
                    переполнения.Add(
                        $"{контрол.GetType().Name} '{контрол.Text}' — низ {границы.Bottom} > достижимая {достижимаяВысота}");
                }

                continue;
            }

            // Контролы контейнеров переработанной вкладки обязаны целиком
            // помещаться в своего родителя: вытекание за нижнюю границу
            // (например, многострочное поле из строки таблицы) — дефект
            // компоновки, даже если контейнер дальше сам прокручиваем.
            if (контейнерыВкладки.Contains(контрол.Parent!)
                && контрол.Bottom > контрол.Parent!.ClientSize.Height)
            {
                переполнения.Add(
                    $"{контрол.GetType().Name} '{контрол.Text}' вытекает из родителя {контрол.Parent.GetType().Name}: низ {контрол.Bottom} > {контрол.Parent.ClientSize.Height}");
            }
        }

        Assert.True(
            переполнения.Count == 0,
            "Контролы ниже достижимого прокруткой контента: " + string.Join("; ", переполнения));
    }

    /// <summary>
    /// Кнопки «Сохранить» и «Отмена» закреплены на форме и видимы
    /// (прокрутка вкладки им не подчиняется).
    /// </summary>
    [Fact]
    public void Карточка_КнопкиСохранитьОтмена_ВидныВКлиентскойОбласти()
    {
        using var форма = ПоказатьКарточку();

        var отмена = Обойти(форма).OfType<Button>().Single(кнопка => кнопка.Text == "Отмена");

        Assert.Null(LayoutAssertions.ПричинаВыходаЗаГраницы(форма.КнопкаСохранить, форма));
        Assert.Null(LayoutAssertions.ПричинаВыходаЗаГраницы(отмена, форма));
        Assert.True(форма.КнопкаСохранить.Visible);
        Assert.True(отмена.Visible);
    }

    // ------------------------------------------------------------------
    // Подписи: одна строка, без обрезания.
    // ------------------------------------------------------------------

    /// <summary>
    /// Подписи колонок реквизитов умещаются в колонке 110 px и не
    /// переносятся: «Наименование:», «Сокращённое:», «Эл. почта:» видны
    /// целиком, высота каждой подписи — одна строка.
    /// </summary>
    [Fact]
    public void Карточка_ПодписиРеквизитов_ОднаСтрокаБезОбрезания()
    {
        using var форма = ПоказатьКарточку();

        var реквизиты = Обойти(форма.СтраницаРеквизитов)
            .OfType<TableLayoutPanel>()
            .Single(таблица => таблица.Controls.OfType<Label>()
                .Any(метка => метка.Text == "Наименование:"));

        var подписи = реквизиты.Controls
            .OfType<Label>()
            .Where(метка => метка.Text.EndsWith(':'))
            .ToList();

        Assert.Contains(подписи, метка => метка.Text == "Наименование:");
        Assert.Contains(подписи, метка => метка.Text == "Сокращённое:");
        Assert.Contains(подписи, метка => метка.Text == "Эл. почта:");

        foreach (var подпись in подписи)
        {
            Assert.True(
                подпись.Width <= 110,
                $"Подпись «{подпись.Text}» шире колонки 110 px: {подпись.Width} — обрезана или переносится.");

            Assert.True(
                подпись.Height <= подпись.Font.Height + 6,
                $"Подпись «{подпись.Text}» перенесена на несколько строк: высота {подпись.Height} при высоте шрифта {подпись.Font.Height}.");
        }
    }

    // ------------------------------------------------------------------
    // Пользовательские поля: реально доступны.
    // ------------------------------------------------------------------

    /// <summary>
    /// Таблица пользовательских полей имеет положительные размеры, три
    /// колонки «Поле», «Значение», «Тег» и строку добавления; панель
    /// пользовательских полей закреплена к низу вкладки и видна в
    /// клиентской области без прокрутки (редизайн 2026-11-08).
    /// </summary>
    [Fact]
    public void Карточка_ПользовательскиеПоля_ПоложительныеРазмерыИКолонки()
    {
        using var форма = ПоказатьКарточку();

        var таблица = форма.ТаблицаПользовательскихПолей;

        Assert.True(таблица.Visible, "Таблица пользовательских полей должна быть видимой.");
        Assert.True(таблица.Width > 0, "Ширина таблицы пользовательских полей должна быть положительной.");
        Assert.True(таблица.Height > 0, "Высота таблицы пользовательских полей должна быть положительной.");

        Assert.Equal(
            new[] { "Поле", "Значение", "Тег" },
            таблица.Columns.Cast<DataGridViewColumn>().Select(колонка => колонка.Name).ToArray());

        Assert.True(таблица.AllowUserToAddRows, "Строка добавления пары «поле/значение» должна быть доступна.");

        var причина = LayoutAssertions.ПричинаВыходаЗаГраницы(таблица, форма);

        Assert.True(
            причина is null,
            $"Таблица пользовательских полей вне клиентской области: {причина}");
    }

    /// <summary>
    /// Ввод пары «поле/значение» в строке добавления обновляет тег
    /// Custom_…: коммит редактирования имени поля фиксируется событием
    /// CellValueChanged, на которое подписана карточка (пробелы имени
    /// заменяются подчёркиваниями по правилам тега).
    /// </summary>
    [Fact]
    public void Карточка_ВводИмениПоля_ОбновляетТегCustom()
    {
        using var форма = ПоказатьКарточку();

        var таблица = форма.ТаблицаПользовательскихПолей;
        var строка = таблица.Rows[таблица.Rows.Count - 1]; // строка добавления

        строка.Cells[0].Value = "Номер договора";
        таблица.CurrentCell = строка.Cells[0];
        таблица.BeginEdit(false);
        таблица.EndEdit();

        Assert.Equal("[Custom_Номер_договора]", строка.Cells[2].Value as string);
    }

    /// <summary>
    /// Прокси-проверка увеличенного системного масштаба (PerMonitorV2
    /// масштабирует и шрифты, и геометрию): при масштабах 100/125/150 %
    /// адресные блоки не пересекаются, кнопки «Сохранить»/«Отмена» видимы,
    /// вкладка «Реквизиты» остаётся прокручиваемой.
    /// </summary>
    [Theory]
    [InlineData(1.0f)] // 100 %
    [InlineData(1.25f)] // 125 %
    [InlineData(1.5f)] // 150 %
    public void Карточка_УвеличенныйМасштаб_КомпоновкаЦела(float масштаб)
    {
        using var форма = ПоказатьКарточку();
        форма.Scale(new SizeF(масштаб, масштаб));
        форма.PerformLayout();
        System.Windows.Forms.Application.DoEvents();

        var редакторы = Обойти(форма).OfType<AddressEditor>().ToList();

        Assert.Equal(3, редакторы.Count);

        for (var первый = 0; первый < редакторы.Count; первый++)
        {
            var границыПервого = ГраницыВ(редакторы[первый], форма.СтраницаРеквизитов);

            for (var второй = первый + 1; второй < редакторы.Count; второй++)
            {
                var границыВторого = ГраницыВ(редакторы[второй], форма.СтраницаРеквизитов);

                Assert.False(
                    границыПервого.IntersectsWith(границыВторого),
                    $"Адресные блоки пересекаются при масштабе {масштаб}: {границыПервого} ∩ {границыВторого}.");
            }
        }

        Assert.Null(LayoutAssertions.ПричинаВыходаЗаГраницы(форма.КнопкаСохранить, форма));

        var прокрутка = Обойти(форма.СтраницаРеквизитов)
            .OfType<ScrollableControl>()
            .Single(панель => панель.AutoScroll);

        Assert.True(прокрутка.AutoScroll);
    }
}
