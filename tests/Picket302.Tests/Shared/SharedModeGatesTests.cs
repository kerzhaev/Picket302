namespace Picket302.Tests.Shared;

/// <summary>
/// Гейты общего режима: функции без сетевого аналога отключаются с
/// объяснением и не имеют локальной поверхности, на которую можно
/// тихо упасть (решения SOURCE-MAP, сценарии 47, 49, 51, 63).
/// </summary>
/// <remarks>
/// Проверяется настоящий состав приложения
/// (<see cref="AppServices.СоздатьОбщийAsync"/>), поднятый против
/// настоящей службы стенда: в нём гейтированные службы отсутствуют,
 /// а шлюз — удалённый. Отказ COM-сервера при сопряжении проверяет
/// <see cref="SharedModeRefusalTests"/>.
/// </remarks>
public sealed class SharedModeGatesTests
{
    [Fact]
    public async Task Общий_состав_Не_Имеет_Локальной_Поверхности_Гейтированных_Функций()
    {
        await using var стенд = await SharedServiceTestHost.ПоднятьAsync();

        using var клиент = await стенд.СоздатьКлиентаAsync("ПК гейтов");

        using var профиль = new Picket302.Tests.Infrastructure.ИзолированныйПрофиль();

        var реквизиты = new SharedClientSettings(
            "127.0.0.1",
            стенд.Порт,
            клиент.Устройство,
            string.Empty,
            SharedFingerprint.ВычислитьОтпечаток(стенд.Сертификат));

        await using var состав = await AppServices.СоздатьОбщийAsync(
            профиль.Пути,
            реквизиты,
            клиент.Секрет,
            реестрОтправителяИзолирован: true,
            реестрЛицензирования: профиль.РеестрЛицензирования);

        // Состав действительно работает в общем режиме: шлюз удалённый,
        // локальной базы нет.
        Assert.True(состав.ОбщийРежим);
        Assert.IsType<RemoteDataGateway>(состав.Данные);
        Assert.Equal(string.Empty, состав.ПутьБазы);
        Assert.Null(состав.ЛокальнаяСессия);

        // Гейтированные функции не имеют локальной реализации, на которую
        // можно было бы тихо упасть: служб нет ни в каком виде.
        Assert.Null(состав.СлужбаВходящих);
        Assert.Null(состав.ТрекерВходящих);
        Assert.Null(состав.МенеджерПользовательскихОтчётов);
        Assert.Null(состав.ПоставщикДанныхОтчётов);

        // Состав связан с настоящей службой: запрос через шлюз возвращает
        // ответ сервера, а не локальную заглушку.
        var группы = await состав.Данные.ПолучитьГруппыAsync();

        Assert.NotNull(группы);
    }

    [Fact]
    public async Task Общий_состав_Работает_С_Общими_Данными_Сервера()
    {
        await using var стенд = await SharedServiceTestHost.ПоднятьAsync();

        using var клиент = await стенд.СоздатьКлиентаAsync("ПК гейтов — данные");

        using var профиль = new Picket302.Tests.Infrastructure.ИзолированныйПрофиль();

        var реквизиты = new SharedClientSettings(
            "127.0.0.1",
            стенд.Порт,
            клиент.Устройство,
            string.Empty,
            SharedFingerprint.ВычислитьОтпечаток(стенд.Сертификат));

        await using var состав = await AppServices.СоздатьОбщийAsync(
            профиль.Пути,
            реквизиты,
            клиент.Секрет,
            реестрОтправителяИзолирован: true,
            реестрЛицензирования: профиль.РеестрЛицензирования);

        // Контрагент, созданный полным составом приложения, виден по
        // отдельному чтению тем же составом: данные не попадают в локальную
        // копию — их нет нигде, кроме общей базы службы.
        var созданный = await состав.Данные.СохранитьКонтрагентаAsync(Контрагент());

        Assert.True(созданный.IsSuccess);

        var страница = await состав.Данные.ПолучитьКонтрагентовAsync(
            new PageRequest(0, 100));

        Assert.Contains(
            страница.Items,
            запись => запись.Id == созданный.Value.Id);
    }

    [Fact]
    public void Сообщения_Гейтов_Общего_Режима_Фиксированы()
    {
        // Каждый гейт отключает функцию с объяснением, а не подменяет её
        // локальным аналогом. Тексты зафиксированы: изменение сообщения
        // без пересмотра гейта ломает этот тест.
        Assert.Equal(
            "Резервное копирование в режиме общей базы выполняет серверная "
            + "служба: копии хранятся в каталоге данных службы на серверном "
            + "компьютере.",
            MainShell.СообщениеАрхивированияВОбщемРежиме);

        Assert.Equal(
            "Перенос данных из предыдущей версии выполняется при первичной настройке "
            + "серверной части. В подключённом режиме общей базы мастер недоступен.",
            MainShell.СообщениеПереносаВОбщемРежиме);

        Assert.Equal(
            "Незавершённые операции есть только в режиме общей базы: запись в "
            + "одиночном режиме не теряет ответов.",
            MainShell.СообщениеНезавершённыхВОдиночномРежиме);

        Assert.Equal(
            "Входящая корреспонденция в режиме общей базы недоступна: сканы "
            + "хранятся на конкретном компьютере и не видны другим рабочим местам.",
            MainShell.СообщениеВходящихВОбщемРежиме);

        Assert.Equal(
            "Пользовательские отчёты в режиме общей базы недоступны: "
            + "отчёты обращаются к базе напрямую, а клиенту общей базы "
            + "произвольные запросы не передаются.",
            MainShell.СообщениеОтчётовВОбщемРежиме);
    }

    private static Counterparty Контрагент() => new()
    {
        Type = CounterpartyType.LegalEntity,
        Name = "ООО «Гейт общего режима»",
        Inn = "7707083893",
        IsActive = true,
        CreatedAt = DateTime.UtcNow,
        PostalAddress = Address.Create(
            "101000",
            ["ООО «Гейт общего режима»", "Управление делами", "ул. Тверская, 12", "корп. 2", "г. Москва", string.Empty]).Value,
    };
}
