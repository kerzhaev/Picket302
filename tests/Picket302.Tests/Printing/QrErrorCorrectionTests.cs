using Picket302.Printing.Codes;
using Xunit;

namespace Picket302.Tests.Printing;

/// <summary>
/// Проверка слоя коррекции ошибок QR-кода (ГОСТ Р 56042-2014; ISO/IEC 18004,
/// раздел 8). Декодер <see cref="Декодер"/> реализован независимо от
/// кодировщика и проверяет синдромы Рида — Соломона, поэтому тест подтверждает
/// не только полезную нагрузку, но и корректность корректирующих кодовых слов.
/// </summary>
public sealed class QrErrorCorrectionTests
{
    private const string ПолезнаяНагрузка = "Платёж 1234,56; адрес 101000, Москва";

    [Fact]
    public void Корректирующие_Кодовые_Слова_Имеют_Нулевые_Синдромы()
    {
        var код = QrEncoder.Encode(ПолезнаяНагрузка, QrErrorCorrectionLevel.Medium);

        Assert.True(
            Декодер.СиндромыНулевые(код),
            "Синдромы Рида — Соломона должны быть нулевыми: корректирующие кодовые слова рассчитаны верно.");

        Assert.Equal(0, Декодер.ИсправитьОшибки(код));
    }

    [Fact]
    public void Повреждённый_Код_Читается_И_Восстанавливает_Полезную_Нагрузку()
    {
        var код = QrEncoder.Encode(ПолезнаяНагрузка, QrErrorCorrectionLevel.Medium);
        var позиции = Декодер.ПозицииМодулейДанных(код);

        Assert.True(позиции.Count > 8, "Код должен содержать достаточно модулей данных.");

        // Версия 1 уровня M: один блок, 10 корректирующих кодовых слов —
        // исправляются до 5 ошибок в блоке. Повреждаем 4 модуля данных.
        var повреждённые = new[] { 0, 3, 6, 9 }
            .Select(индекс => позиции[(индекс * позиции.Count) / 12])
            .Distinct()
            .ToArray();

        Assert.Equal(4, повреждённые.Length);

        var модули = new bool[код.Size * код.Size];

        for (var y = 0; y < код.Size; y++)
        {
            for (var x = 0; x < код.Size; x++)
            {
                модули[(y * код.Size) + x] = код.GetModule(x, y);
            }
        }

        foreach (var (x, y) in повреждённые)
        {
            модули[(y * код.Size) + x] = !модули[(y * код.Size) + x];
        }

        var повреждённый = new QrCode(код.Version, код.ErrorCorrection, код.MaskPattern, модули);

        Assert.False(
            Декодер.СиндромыНулевые(повреждённый),
            "Повреждённый код должен давать ненулевые синдромы.");

        Assert.Equal(
            4,
            Декодер.ИсправитьОшибки(повреждённый));

        Assert.Equal(
            ПолезнаяНагрузка,
            Декодер.ПрочитатьПолезнуюНагрузку(повреждённый));

        Assert.True(
            Декодер.СиндромыНулевые(повреждённый, исправлять: true),
            "После исправления синдромы должны стать нулевыми.");
    }
}
