    /// <summary>
    /// Импортирует контрагентов из файла выгрузки 1С (ТЗ §8.5, функция 72).
    /// </summary>
    /// <param name="filePath">Путь к файлу выгрузки.</param>
    /// <param name="version">Версия выгрузки 1С.</param>
    /// <returns>
    /// Пакет импорта с записями контрагентов и предупреждениями разбора.
    /// </returns>
    /// <exception cref="ArgumentException">Путь к файлу не задан.</exception>
    /// <exception cref="FileNotFoundException">Файл выгрузки не найден.</exception>
    /// <exception cref="IOException">Файл выгрузки не удалось прочитать.</exception>
    public ImportBatchResult ImportFromOneC(string filePath, OneCVersion version)
    {
        if (string.IsNullOrWhiteSpace(filePath))
        {
            throw new ArgumentException("Путь к файлу выгрузки 1С не задан.", nameof(filePath));
        }

        if (!File.Exists(filePath))
        {
            throw new FileNotFoundException($"Файл выгрузки 1С не найден: {filePath}", filePath);
        }

        var содержимое = ПрочитатьФайл(filePath);
        var формат = version.GetSourceFormatName();
        var имяФайла = Path.GetFileName(filePath);
        var времяИмпорта = DateTime.Now;
        var описаниеИсточника = $"Импорт {формат} от {времяИмпорта:dd.MM.yyyy} из {имяФайла}";

        var предупреждения = new List<string>();
        var записи = РазобратьСодержимое(содержимое, описаниеИсточника, предупреждения);

        var пакет = new ImportBatch
        {
            SourceFormat = формат,
            SourceFile = имяФайла,
            ImportedAt = времяИмпорта,
            Records = записи,
        };

        return new ImportBatchResult(пакет, предупреждения);
    }

    /// <summary>
    /// Читает файл выгрузки с автоопределением кодировки: UTF-8 (с маркером и
    /// без), UTF-16 либо устаревшая cp1251 (ТЗ §10.1).
    /// </summary>
    /// <param name="filePath">Путь к файлу выгрузки.</param>
    /// <returns>Текстовое содержимое файла.</returns>
    private static string ПрочитатьФайл(string filePath)
    {
        byte[] байты;

        try
        {
            байты = File.ReadAllBytes(filePath);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            throw new IOException($"Файл выгрузки 1С не удалось прочитать: {filePath}", ex);
        }

        return Декодировать(байты);
    }

    /// <summary>
    /// Определяет кодировку файла выгрузки и приводит его к тексту.
    /// </summary>
    /// <param name="байты">Содержимое файла.</param>
    /// <returns>Текстовое содержимое файла.</returns>
    private static string Декодировать(byte[] байты)
    {
        if (байты.Length >= 3 && байты[0] == 0xEF && байты[1] == 0xBB && байты[2] == 0xBF)
        {
            return new UTF8Encoding(false).GetString(байты, 3, байты.Length - 3);
        }

        if (байты.Length >= 2 && байты[0] == 0xFF && байты[1] == 0xFE)
        {
            return Encoding.Unicode.GetString(байты, 2, байты.Length - 2);
        }

        if (байты.Length >= 2 && байты[0] == 0xFE && байты[1] == 0xFF)
        {
            return Encoding.BigEndianUnicode.GetString(байты, 2, байты.Length - 2);
        }

        try
        {
            return new UTF8Encoding(false, true).GetString(байты);
        }
        catch (DecoderFallbackException)
        {
            return ДекодироватьCp1251(байты);
        }
    }

    /// <summary>
    /// Декодирует файл в кодировке cp1251 (устаревшая выгрузка 1С 7.7).
    /// </summary>
    /// <param name="байты">Содержимое файла.</param>
    /// <returns>Текстовое содержимое файла.</returns>
    /// <remarks>
    /// Декодирование выполняется штатной кодировкой windows-1251
    /// (<see cref="TextEncodingDetector.Cp1251"/>; F-D3): ручная таблица
    /// прежде не переводила диапазон 0x80–0xBF (тире «—», кавычки «„“»,
    /// знак «№»), и символы искажались.
    /// </remarks>
    private static string ДекодироватьCp1251(byte[] байты)
    {
        return TextEncodingDetector.Cp1251.GetString(байты);
    }

    /// <summary>
    /// Определяет формат содержимого файла и разбирает его (XML либо текст).
    /// </summary>
    /// <param name="содержимое">Содержимое файла выгрузки.</param>
    /// <param name="описаниеИсточника">Описание источника для поля «Источник».</param>
    /// <param name="предупреждения">Накопитель предупреждений разбора.</param>
    /// <returns>Записи пакета импорта.</returns>
    private List<ImportRecord> РазобратьСодержимое(
        string содержимое,
        string описаниеИсточника,
        List<string> предупреждения)
    {
        var записи = new List<ImportRecord>();

        if (string.IsNullOrWhiteSpace(содержимое))
        {
            предупреждения.Add("Файл выгрузки 1С пуст: импортировать нечего.");
            return записи;
        }

        return ПохожеНаXml(содержимое)
            ? РазобратьXml(содержимое, описаниеИсточника, предупреждения)
            : РазобратьТекст(содержимое, описаниеИсточника, предупреждения);
    }

    /// <summary>
    /// Определяет, что содержимое файла является XML-документом.
    /// </summary>
    /// <param name="содержимое">Содержимое файла выгрузки.</param>
    /// <returns><see langword="true"/>, если содержимое начинается с XML-элемента.</returns>
    private static bool ПохожеНаXml(string содержимое)
    {
        var начало = содержимое.AsSpan().TrimStart();

        return начало.StartsWith("<", StringComparison.Ordinal);
    }

    /// <summary>
    /// Разбирает XML-выгрузку 1С (ТЗ §8.5, функция 72).
    /// </summary>
    /// <param name="содержимое">Содержимое файла выгрузки.</param>
    /// <param name="описаниеИсточника">Описание источника для поля «Источник».</param>
    /// <param name="предупреждения">Накопитель предупреждений разбора.</param>
    /// <returns>Записи пакета импорта.</returns>
    private List<ImportRecord> РазобратьXml(
        string содержимое,
        string описаниеИсточника,
        List<string> предупреждения)
    {
        var записи = new List<ImportRecord>();

        XDocument документ;

        try
        {
            документ = XDocument.Parse(содержимое);
        }
        catch (XmlException ex)
        {
            предупреждения.Add($"Файл выгрузки 1С не разобран как XML: {ex.Message}");
            return записи;
        }

        var корень = документ.Root;

        if (корень is null)
        {
            предупреждения.Add("Файл выгрузки 1С не содержит корневого элемента XML.");
            return записи;
        }

        var номер = 0;

        if (ЭтоКонтрагент(НормализоватьКлюч(корень.Name.LocalName)))
        {
            var записьКорня = СобратьЗапись(
                корень,
                номер: 1,
                описаниеИсточника,
                предупреждения);

            if (записьКорня is not null)
            {
                записи.Add(записьКорня);
            }

            return записи;
        }

        ОбойтиУзлы(корень, ref номер, записи, предупреждения, описаниеИсточника);
        return записи;
    }

    /// <summary>
    /// Обходит XML-документ и собирает записи контрагентов.
    /// </summary>
    /// <param name="узел">Текущий узел обхода.</param>
    /// <param name="номер">Счётчик записей (нумерация с единицы).</param>
    /// <param name="записи">Накопитель записей пакета.</param>
    /// <param name="предупреждения">Накопитель предупреждений разбора.</param>
    /// <param name="описаниеИсточника">Описание источника для поля «Источник».</param>
    private void ОбойтиУзлы(
        XElement узел,
        ref int номер,
        List<ImportRecord> записи,
        List<string> предупреждения,
        string описаниеИсточника)
    {
        foreach (var потомок in узел.Elements())
        {
            var имя = НормализоватьКлюч(потомок.Name.LocalName);

            if (ЭтоКонтрагент(имя))
            {
                номер++;
                var запись = СобратьЗапись(потомок, номер, описаниеИсточника, предупреждения);

                if (запись is not null)
                {
                    записи.Add(запись);
                }

                continue;
            }

            if (ЭтоБлок(имя))
            {
                var вложенный = потомок
                    .Descendants()
                    .FirstOrDefault(элемент => ЭтоКонтрагент(НормализоватьКлюч(элемент.Name.LocalName)));

                if (вложенный is not null)
                {
                    номер++;
                    var записьВложенная = СобратьЗапись(вложенный, номер, описаниеИсточника, предупреждения);

                    if (записьВложенная is not null)
                    {
                        записи.Add(записьВложенная);
                    }

                    continue;
                }

                if (имя == "пакет")
                {
                    if (!СодержитКонтрагентов(потомок))
                    {
                        предупреждения.Add(
                            $"Блок «{потомок.Name.LocalName}» пропущен: не найден тег контрагента.");
                        continue;
                    }
                }
                else if (!СодержитНаименование(потомок))
                {
                    предупреждения.Add(
                        $"Блок «{потомок.Name.LocalName}» пропущен: не найден тег контрагента.");
                    continue;
                }

                номер++;
                var записьБлока = СобратьЗапись(потомок, номер, описаниеИсточника, предупреждения);

                if (записьБлока is not null)
                {
                    записи.Add(записьБлока);
                }

                continue;
            }

            ОбойтиУзлы(потомок, ref номер, записи, предупреждения, описаниеИсточника);
        }
    }

    /// <summary>
    /// Определяет, является ли XML-элемент записью контрагента.
    /// </summary>
    /// <param name="имя">Нормализованное имя элемента.</param>
    /// <returns><see langword="true"/>, если элемент содержит контрагента.</returns>
    private static bool ЭтоКонтрагент(string имя)
        => ИменаКонтрагентов.Contains(имя, StringComparer.Ordinal);

    /// <summary>
    /// Определяет, является ли XML-элемент блоком выгрузки.
    /// </summary>
    /// <param name="имя">Нормализованное имя элемента.</param>
    /// <returns><see langword="true"/>, если элемент является блоком выгрузки.</returns>
    private static bool ЭтоБлок(string имя)
        => ИменаБлоков.Contains(имя, StringComparer.Ordinal);

    /// <summary>
    /// Определяет, содержит ли блок выгрузки контрагента (по признаку
    /// «Содержимое» пакета либо по наличию наименования).
    /// </summary>
    /// <param name="блок">Блок выгрузки.</param>
    /// <returns><see langword="true"/>, если блок описывает контрагента.</returns>
    private static bool СодержитКонтрагентов(XElement блок)
    {
        var содержание = блок
            .Attributes()
            .FirstOrDefault(атрибут => атрибут.Name.LocalName == "Содержимое")?
            .Value;

        if (содержание is not null
            && содержание.Contains("онтрагент", StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        return СодержитНаименование(блок);
    }

    /// <summary>
    /// Определяет, содержит ли элемент наименование контрагента.
    /// </summary>
    /// <param name="узел">Проверяемый элемент.</param>
    /// <returns><see langword="true"/>, если наименование найдено.</returns>
    private static bool СодержитНаименование(XElement узел)
        => узел
            .Descendants()
            .Any(элемент => ПолеПоКлючу(ОпределитьКлюч(элемент)) == ПолеРеквизита.Имя);

    /// <summary>
    /// Собирает запись импорта из XML-элемента контрагента.
    /// </summary>
    /// <param name="узел">Элемент с данными контрагента.</param>
    /// <param name="номер">Номер записи в пакете (нумерация с единицы).</param>
    /// <param name="описаниеИсточника">Описание источника для поля «Источник».</param>
    /// <param name="предупреждения">Накопитель предупреждений разбора.</param>
    /// <returns>Запись импорта либо <see langword="null"/>, если запись пропущена.</returns>
    private ImportRecord? СобратьЗапись(
        XElement узел,
        int номер,
        string описаниеИсточника,
        List<string> предупреждения)
    {
        var реквизиты = new РеквизитыКонтрагента
        {
            Черновик = { Source = описаниеИсточника },
        };

        var имяЭлемента = НормализоватьКлюч(узел.Name.LocalName);

        if (имяЭлемента == "naturalperson")
        {
            реквизиты.Тип = CounterpartyType.NaturalPerson;
        }
        else if (имяЭлемента == "legalperson")
        {
            реквизиты.Тип = CounterpartyType.LegalEntity;
        }

        СобратьРеквизиты(узел, реквизиты);

        return ЗавершитьЗапись(
            реквизиты,
            номер,
            $"Блок «{узел.Name.LocalName}»",
            предупреждения);
    }

    /// <summary>
    /// Собирает реквизиты контрагента из XML-элемента и его потомков.
    /// Неизвестные элементы игнорируются (ТЗ §8.5, функция 72).
    /// </summary>
    /// <param name="узел">Элемент с данными контрагента.</param>
    /// <param name="реквизиты">Накопитель реквизитов.</param>
    private void СобратьРеквизиты(XElement узел, РеквизитыКонтрагента реквизиты)
    {
        foreach (var потомок in узел.Elements())
        {
            var поле = ОпределитьПоле(потомок);

            switch (поле)
            {
                case ПолеРеквизита.Неизвестное:
                    СобратьРеквизиты(потомок, реквизиты);
                    continue;

                case ПолеРеквизита.ПочтовыйАдрес:
                case ПолеРеквизита.ЮридическийАдрес:
                case ПолеРеквизита.ФактическийАдрес:
                    ЗаполнитьАдресИзXml(реквизиты, поле, потомок);
                    continue;

                default:
                    ПрименитьЗначение(реквизиты, поле, потомок.Value);
                    continue;
            }
        }
    }

    /// <summary>
    /// Определяет реквизит по имени XML-элемента; при наличии атрибута «Имя»
    /// ему отдаётся предпочтение (формат 1С 8.x).
    /// </summary>
    /// <param name="узел">XML-элемент.</param>
    /// <returns>Реквизит либо <see cref="ПолеРеквизита.Неизвестное"/>.</returns>
    private static ПолеРеквизита ОпределитьПоле(XElement узел)
    {
        var поАтрибуту = ПолеПоКлючу(ОпределитьКлюч(узел));

        return поАтрибуту != ПолеРеквизита.Неизвестное
            ? поАтрибуту
            : ПолеПоКлючу(узел.Name.LocalName);
    }

    /// <summary>
    /// Возвращает имя реквизита: значение атрибута «Имя» либо имя элемента.
    /// </summary>
    /// <param name="узел">XML-элемент.</param>
    /// <returns>Имя реквизита.</returns>
    private static string ОпределитьКлюч(XElement узел)
    {
        var атрибут = узел
            .Attributes()
            .FirstOrDefault(атрибут => атрибут.Name.LocalName == "Имя");

        return атрибут?.Value ?? узел.Name.LocalName;
    }

    /// <summary>
    /// Заполняет адрес контрагента по XML-элементу: структурированный адрес
    /// (<c>ZipCode</c>, <c>City</c>, <c>Province</c>, <c>AddressLine</c>) либо
    /// составная строка адреса.
    /// </summary>
    /// <param name="реквизиты">Накопитель реквизитов.</param>
    /// <param name="поле">Вид адреса.</param>
    /// <param name="узел">XML-элемент адреса.</param>
    private static void ЗаполнитьАдресИзXml(
        РеквизитыКонтрагента реквизиты,
        ПолеРеквизита поле,
        XElement узел)
    {
        var данные = АдресПоПолю(реквизиты, поле);
        var значение = узел.Value?.Trim() ?? string.Empty;

        if (значение.Length == 0)
        {
            return;
        }

        var дети = узел
            .Elements()
            .Where(элемент => !ЭтоЗначение(элемент))
            .ToList();

        if (дети.Count == 0)
        {
            данные.Исходный = значение;
            return;
        }

        данные.Структурированный = true;
        данные.Zip ??= НайтиЗначение(дети, "zipcode", "индекс", "почтовыйиндекс");
        данные.Город ??= НайтиЗначение(дети, "city", "город", "населенныйпункт");
        данные.Регион ??= НайтиЗначение(дети, "province", "область", "регион");
        данные.Улица ??= НайтиЗначение(дети, "addressline", "улица", "адресстроки");
        данные.Дом ??= НайтиЗначение(дети, "дом");
        данные.Квартира ??= НайтиЗначение(дети, "квартира", "офис");
    }

    /// <summary>
    /// Определяет, является ли XML-элемент обёрткой значения
    /// (<c>&lt;Значение&gt;</c>).
    /// </summary>
    /// <param name="узел">XML-элемент.</param>
    /// <returns><see langword="true"/>, если элемент является обёрткой значения.</returns>
    private static bool ЭтоЗначение(XElement узел)
    {
        var имя = НормализоватьКлюч(узел.Name.LocalName);

        return имя == "значение" || имя == "value";
    }

    /// <summary>
    /// Ищет текст первого потомка с одним из указанных имён реквизита.
    /// </summary>
    /// <param name="элементы">Потомки проверяемого элемента.</param>
    /// <param name="имена">Нормализованные имена искомых реквизитов.</param>
    /// <returns>Значение реквизита либо <see langword="null"/>.</returns>
    private static string? НайтиЗначение(IEnumerable<XElement> элементы, params string[] имена)
    {
        foreach (var элемент in элементы)
        {
            var ключ = НормализоватьКлюч(ОпределитьКлюч(элемент));

            if (имена.Contains(ключ, StringComparer.Ordinal))
            {
                var значение = элемент.Value?.Trim();

                if (!string.IsNullOrEmpty(значение))
                {
                    return значение;
                }
            }
        }

        return null;
    }

    /// <summary>
    /// Возвращает данные адреса соответствующего вида.
    /// </summary>
    /// <param name="реквизиты">Накопитель реквизитов.</param>
    /// <param name="поле">Вид адреса.</param>
    /// <returns>Данные адреса.</returns>
    private static ДанныеАдреса АдресПоПолю(РеквизитыКонтрагента реквизиты, ПолеРеквизита поле) => поле switch
    {
        ПолеРеквизита.ЮридическийАдрес => реквизиты.ЮридическийАдрес,
        ПолеРеквизита.ФактическийАдрес => реквизиты.ФактическийАдрес,
        _ => реквизиты.ПочтовыйАдрес,
    };

    /// <summary>
    /// Присваивает реквизиту значение: первое непустое значение сохраняется.
    /// </summary>
    /// <param name="реквизиты">Накопитель реквизитов.</param>
    /// <param name="поле">Реквизит.</param>
    /// <param name="значение">Значение реквизита из файла.</param>
    private static void ПрименитьЗначение(
        РеквизитыКонтрагента реквизиты,
        ПолеРеквизита поле,
        string? значение)
    {
        var текст = значение?.Trim() ?? string.Empty;

        if (текст.Length == 0)
        {
            return;
        }

        реквизиты.ЕстьДанные = true;

        switch (поле)
        {
            case ПолеРеквизита.Имя:
                if (реквизиты.Черновик.Name.Length == 0)
                {
                    реквизиты.Черновик.Name = текст;
                }

                break;

            case ПолеРеквизита.СокращенноеИмя:
                реквизиты.Черновик.ShortName ??= текст;
                break;

            case ПолеРеквизита.ИНН:
                реквизиты.Черновик.Inn ??= текст;
                break;

            case ПолеРеквизита.КПП:
                реквизиты.Черновик.Kpp ??= текст;
                break;

            case ПолеРеквизита.ОГРН:
                реквизиты.Черновик.Ogrn ??= текст;
                break;

            case ПолеРеквизита.Телефон:
                реквизиты.Черновик.Phone ??= текст;
                break;

            case ПолеРеквизита.Email:
                реквизиты.Черновик.Email ??= текст;
                break;

            case ПолеРеквизита.Примечание:
                реквизиты.Черновик.Note ??= текст;
                break;

            case ПолеРеквизита.Счет:
                реквизиты.Счет ??= текст;
                break;

            case ПолеРеквизита.Банк:
                реквизиты.Банк ??= текст;
                break;

            case ПолеРеквизита.БИК:
                реквизиты.БИК ??= текст;
                break;

            case ПолеРеквизита.Индекс:
                реквизиты.Индекс ??= текст;
                break;

            case ПолеРеквизита.Фамилия:
                реквизиты.Фамилия = текст;
                break;

            case ПолеРеквизита.ИмяОтчество:
                реквизиты.ИмяОтчество = текст;
                break;

            case ПолеРеквизита.Отчество:
                реквизиты.Отчество = текст;
                break;

            case ПолеРеквизита.Тип:
                реквизиты.Тип = ОпределитьТип(текст);
                break;

            default:
                break;
        }
    }

    /// <summary>
    /// Определяет тип контрагента по значению реквизита «Тип».
    /// </summary>
    /// <param name="значение">Значение реквизита «Тип».</param>
    /// <returns>Тип контрагента либо <see langword="null"/>, если тип не распознан.</returns>
    private static CounterpartyType? ОпределитьТип(string значение)
    {
        var текст = значение.ToLowerInvariant();

        if (текст.Contains("физическ", StringComparison.Ordinal))
        {
            return CounterpartyType.NaturalPerson;
        }

        if (текст.Contains("юридическ", StringComparison.Ordinal)
            || текст.Contains("организац", StringComparison.Ordinal))
        {
            return CounterpartyType.LegalEntity;
        }

        return null;
    }

    /// <summary>
    /// Разбирает текстовую выгрузку 1С (ТЗ §8.5, функция 72).
    /// </summary>
    /// <param name="содержимое">Содержимое файла выгрузки.</param>
    /// <param name="описаниеИсточника">Описание источника для поля «Источник».</param>
    /// <param name="предупреждения">Накопитель предупреждений разбора.</param>
    /// <returns>Записи пакета импорта.</returns>
    private List<ImportRecord> РазобратьТекст(
        string содержимое,
        string описаниеИсточника,
        List<string> предупреждения)
    {
        var строки = РазделитьНаСтроки(содержимое);
        var разделитель = ОпределитьРазделитель(строки);

        return разделитель == '\0'
            ? РазобратьПарыЗначений(строки, описаниеИсточника, предупреждения)
            : РазобратьТаблицу(строки, разделитель, описаниеИсточника, предупреждения);
    }

    /// <summary>
    /// Делит содержимое файла на строки с сохранением номеров строк.
    /// </summary>
    /// <param name="содержимое">Содержимое файла выгрузки.</param>
    /// <returns>Строки файла.</returns>
    private static string[] РазделитьНаСтроки(string содержимое)
        => содержимое
            .Replace("\r\n", "\n", StringComparison.Ordinal)
            .Replace('\r', '\n')
            .Split('\n');

    /// <summary>
    /// Определяет разделитель столбцов текстовой выгрузки: «точка с запятой»
    /// либо табуляция. Отсутствие обоих разделителей означает форму
    /// «ключ=значение».
    /// </summary>
    /// <param name="строки">Строки файла выгрузки.</param>
    /// <returns>Разделитель столбцов либо <c>'\0'</c> для формы «ключ=значение».</returns>
    private static char ОпределитьРазделитель(IReadOnlyList<string> строки)
    {
        var точкаСЗапятой = 0;
        var табуляция = 0;
        var рассмотрено = 0;

        foreach (var строка in строки)
        {
            if (строка.Trim().Length == 0)
            {
                continue;
            }

            if (строка.Contains(РазделительПар) && строка.Contains('='))
            {
                return '\0';
            }

            точкаСЗапятой += строка.Count(символ => символ == РазделительТочкаСЗапятой);
            табуляция += строка.Count(символ => символ == РазделительТабуляция);

            рассмотрено++;

            if (рассмотрено >= 20)
            {
                break;
            }
        }

        if (точкаСЗапятой == 0 && табуляция == 0)
        {
            return '\0';
        }

        return табуляция > точкаСЗапятой ? РазделительТабуляция : РазделительТочкаСЗапятой;
    }

    /// <summary>
    /// Разбирает табличную текстовую выгрузку 1С 7.7.
    /// </summary>
    /// <param name="строки">Строки файла выгрузки.</param>
    /// <param name="разделитель">Разделитель столбцов.</param>
    /// <param name="описаниеИсточника">Описание источника для поля «Источник».</param>
    /// <param name="предупреждения">Накопитель предупреждений разбора.</param>
    /// <returns>Записи пакета импорта.</returns>
    private List<ImportRecord> РазобратьТаблицу(
        string[] строки,
        char разделитель,
        string описаниеИсточника,
        List<string> предупреждения)
    {
        var записи = new List<ImportRecord>();
        string[]? заголовок = null;

        for (var i = 0; i < строки.Length; i++)
        {
            var строка = строки[i].Trim();

            if (строка.Length == 0)
            {
                continue;
            }

            var номерСтроки = i + 1;
            var ячейки = РазделитьЯчейки(строка, разделитель);

            if (ЭтоПарыЗначений(ячейки))
            {
                var записьПар = СобратьЗаписьИзПар(
                    ячейки,
                    номерСтроки,
                    описаниеИсточника,
                    предупреждения);

                if (записьПар is not null)
                {
                    записи.Add(записьПар);
                }

                continue;
            }

            if (ЯвляетсяЗаголовком(ячейки))
            {
                заголовок = ячейки;
                continue;
            }

            if (заголовок is null)
            {
                // Первая строка файла без распознанного заголовка принимается за заголовок.
                заголовок = ячейки;
                continue;
            }

            if (ячейки.Length > заголовок.Length)
            {
                предупреждения.Add(
                    $"Строка {номерСтроки}: число полей ({ячейки.Length}) больше числа полей заголовка "
                    + $"({заголовок.Length}) — запись пропущена.");
                continue;
            }

            var записьСтроки = СобратьЗаписьИзЯчеек(
                ячейки,
                заголовок,
                номерСтроки,
                описаниеИсточника,
                предупреждения);

            if (записьСтроки is not null)
            {
                записи.Add(записьСтроки);
            }
        }

        return записи;
    }

    /// <summary>
    /// Определяет, является ли строка заголовком таблицы: в ней должны быть
    /// узнаваемые имена реквизитов.
    /// </summary>
    /// <param name="ячейки">Ячейки строки.</param>
    /// <returns><see langword="true"/>, если строка является заголовком.</returns>
    private static bool ЯвляетсяЗаголовком(string[] ячейки)
    {
        var известных = ячейки.Count(
            ячейка => ПолеПоКлючу(ячейка) != ПолеРеквизита.Неизвестное);

        return известных >= 2 || (известных == 1 && ячейки.Length == 1);
    }

    /// <summary>
    /// Определяет, задана ли строка в форме «ключ=значение».
    /// </summary>
    /// <param name="ячейки">Ячейки строки.</param>
    /// <returns><see langword="true"/>, если строка задана парами «ключ=значение».</returns>
    private static bool ЭтоПарыЗначений(string[] ячейки)
    {
        if (ячейки.Length == 0)
        {
            return false;
        }

        var позиция = ячейки[0].IndexOf('=', StringComparison.Ordinal);

        return позиция > 0
            && ПолеПоКлючу(ячейки[0][..позиция]) != ПолеРеквизита.Неизвестное;
    }

    /// <summary>
    /// Делит строку на ячейки по разделителю; ведущие пустые ячейки отбрасываются
    /// (строка может начинаться с разделителя).
    /// </summary>
    /// <param name="строка">Строка файла выгрузки.</param>
    /// <param name="разделитель">Разделитель столбцов.</param>
    /// <returns>Ячейки строки.</returns>
    private static string[] РазделитьЯчейки(string строка, char разделитель)
    {
        var ячейки = строка
            .Split(разделитель, StringSplitOptions.TrimEntries)
            .ToList();

        while (ячейки.Count > 0 && ячейки[0].Length == 0)
        {
            ячейки.RemoveAt(0);
        }

        return ячейки.ToArray();
    }

    /// <summary>
    /// Собирает запись импорта из строки таблицы.
    /// </summary>
    /// <param name="ячейки">Ячейки строки.</param>
    /// <param name="заголовок">Заголовок таблицы.</param>
    /// <param name="номерСтроки">Номер строки файла (нумерация с единицы).</param>
    /// <param name="описаниеИсточника">Описание источника для поля «Источник».</param>
    /// <param name="предупреждения">Накопитель предупреждений разбора.</param>
    /// <returns>Запись импорта либо <see langword="null"/>, если запись пропущена.</returns>
    private ImportRecord? СобратьЗаписьИзЯчеек(
        string[] ячейки,
        string[] заголовок,
        int номерСтроки,
        string описаниеИсточника,
        List<string> предупреждения)
    {
        var реквизиты = new РеквизитыКонтрагента
        {
            Черновик = { Source = описаниеИсточника },
        };

        for (var i = 0; i < ячейки.Length && i < заголовок.Length; i++)
        {
            var поле = ПолеПоКлючу(заголовок[i]);

            if (поле == ПолеРеквизита.Неизвестное)
            {
                continue;
            }

            var значение = ячейки[i].Trim();

            if (поле is ПолеРеквизита.ПочтовыйАдрес
                or ПолеРеквизита.ЮридическийАдрес
                or ПолеРеквизита.ФактическийАдрес)
            {
                ЗаполнитьАдресСтрокой(реквизиты, поле, значение);
                continue;
            }

            ПрименитьЗначение(реквизиты, поле, значение);
        }

        return ЗавершитьЗапись(реквизиты, номерСтроки, $"Строка {номерСтроки}", предупреждения);
    }

    /// <summary>
    /// Собирает запись импорта из строки вида «ключ=значение|ключ=значение».
    /// </summary>
    /// <param name="ячейки">Ячейки строки.</param>
    /// <param name="номерСтроки">Номер строки файла (нумерация с единицы).</param>
    /// <param name="описаниеИсточника">Описание источника для поля «Источник».</param>
    /// <param name="предупреждения">Накопитель предупреждений разбора.</param>
    /// <returns>Запись импорта либо <see langword="null"/>, если запись пропущена.</returns>
    private ImportRecord? СобратьЗаписьИзПар(
        string[] ячейки,
        int номерСтроки,
        string описаниеИсточника,
        List<string> предупреждения)
    {
        var реквизиты = new РеквизитыКонтрагента
        {
            Черновик = { Source = описаниеИсточника },
        };

        ПрименитьПары(реквизиты, ячейки);

        return ЗавершитьЗапись(реквизиты, номерСтроки, $"Строка {номерСтроки}", предупреждения);
    }

    /// <summary>
    /// Разбирает текстовую выгрузку 1С в форме «ключ=значение|ключ=значение».
    /// Новая запись начинается с нового наименования либо с пустой строки.
    /// </summary>
    /// <param name="строки">Строки файла выгрузки.</param>
    /// <param name="описаниеИсточника">Описание источника для поля «Источник».</param>
    /// <param name="предупреждения">Накопитель предупреждений разбора.</param>
    /// <returns>Записи пакета импорта.</returns>
    private List<ImportRecord> РазобратьПарыЗначений(
        string[] строки,
        string описаниеИсточника,
        List<string> предупреждения)
    {
        var записи = new List<ImportRecord>();
        РеквизитыКонтрагента? текущие = null;
        var номерСтрокиНачала = 0;

        for (var i = 0; i < строки.Length; i++)
        {
            var строка = строки[i].Trim();
            var номерСтроки = i + 1;

            if (строка.Length == 0)
            {
                if (текущие is not null)
                {
                    var записьПустой = ЗавершитьЗапись(
                        текущие,
                        номерСтрокиНачала,
                        $"Строка {номерСтрокиНачала}",
                        предупреждения);

                    if (записьПустой is not null)
                    {
                        записи.Add(записьПустой);
                    }

                    текущие = null;
                }

                continue;
            }

            foreach (var пара in РазделитьПары(строка))
            {
                var (ключ, значение) = РазделитьПара(пара);
                var поле = ПолеПоКлючу(ключ);

                if (поле == ПолеРеквизита.Неизвестное)
                {
                    continue;
                }

                if (поле == ПолеРеквизита.Имя && текущие is not null && текущие.ЕстьДанные)
                {
                    var записьПред = ЗавершитьЗапись(
                        текущие,
                        номерСтрокиНачала,
                        $"Строка {номерСтрокиНачала}",
                        предупреждения);

                    if (записьПред is not null)
                    {
                        записи.Add(записьПред);
                    }

                    текущие = null;
                }

                текущие ??= new РеквизитыКонтрагента
                {
                    Черновик = { Source = описаниеИсточника },
                };

                if (текущие.Черновик.Name.Length == 0 && текущие.ЕстьДанные == false)
                {
                    номерСтрокиНачала = номерСтроки;
                }

                if (поле is ПолеРеквизита.ПочтовыйАдрес
                    or ПолеРеквизита.ЮридическийАдрес
                    or ПолеРеквизита.ФактическийАдрес)
                {
                    ЗаполнитьАдресСтрокой(текущие, поле, значение);
                    continue;
                }

                ПрименитьЗначение(текущие, поле, значение);
            }
        }

        if (текущие is not null)
        {
            var записьПоследняя = ЗавершитьЗапись(
                текущие,
                номерСтрокиНачала,
                $"Строка {номерСтрокиНачала}",
                предупреждения);

            if (записьПоследняя is not null)
            {
                записи.Add(записьПоследняя);
            }
        }

        return записи;
    }

    /// <summary>
    /// Присваивает реквизитам значения из строки вида «ключ=значение».
    /// </summary>
    /// <param name="реквизиты">Накопитель реквизитов.</param>
    /// <param name="пары">Ячейки строки с парами «ключ=значение».</param>
    private static void ПрименитьПары(РеквизитыКонтрагента реквизиты, string[] пары)
    {
        foreach (var пара in пары)
        {
            var (ключ, значение) = РазделитьПара(пара);
            var поле = ПолеПоКлючу(ключ);

            if (поле == ПолеРеквизита.Неизвестное)
            {
                continue;
            }

            if (поле is ПолеРеквизита.ПочтовыйАдрес
                or ПолеРеквизита.ЮридическийАдрес
                or ПолеРеквизита.ФактическийАдрес)
            {
                ЗаполнитьАдресСтрокой(реквизиты, поле, значение);
                continue;
            }

            ПрименитьЗначение(реквизиты, поле, значение);
        }
    }

    /// <summary>
    /// Делит строку на пары «ключ=значение».
    /// </summary>
    /// <param name="строка">Строка файла выгрузки.</param>
    /// <returns>Пары строки.</returns>
    private static string[] РазделитьПары(string строка)
    {
        if (строка.Contains(РазделительПар))
        {
            return строка.Split(РазделительПар, StringSplitOptions.TrimEntries);
        }

        if (строка.Contains(РазделительТочкаСЗапятой))
        {
            return строка.Split(РазделительТочкаСЗапятой, StringSplitOptions.TrimEntries);
        }

        return [строка];
    }

    /// <summary>
    /// Разделяет пару «ключ=значение» на ключ и значение.
    /// </summary>
    /// <param name="пара">Пара вида «ключ=значение» либо «ключ: значение».</param>
    /// <returns>Ключ и значение пары.</returns>
    private static (string Ключ, string Значение) РазделитьПара(string пара)
    {
        var позиция = пара.IndexOf('=', StringComparison.Ordinal);

        if (позиция > 0)
        {
            return (пара[..позиция].Trim(), пара[(позиция + 1)..].Trim());
        }

        позиция = пара.IndexOf(':', StringComparison.Ordinal);

        if (позиция > 0)
        {
            var ключ = пара[..позиция].Trim();

            if (ПолеПоКлючу(ключ) != ПолеРеквизита.Неизвестное)
            {
                return (ключ, пара[(позиция + 1)..].Trim());
            }
        }

        return (пара.Trim(), string.Empty);
    }

    /// <summary>
    /// Заполняет адрес контрагента составной строкой адреса.
    /// </summary>
    /// <param name="реквизиты">Накопитель реквизитов.</param>
    /// <param name="поле">Вид адреса.</param>
    /// <param name="значение">Составная строка адреса.</param>
    private static void ЗаполнитьАдресСтрокой(
        РеквизитыКонтрагента реквизиты,
        ПолеРеквизита поле,
        string значение)
    {
        var текст = значение.Trim();

        if (текст.Length == 0)
        {
            return;
        }

        var данные = АдресПоПолю(реквизиты, поле);

        if (данные.Исходный is null)
        {
            данные.Исходный = текст;
        }
    }

    /// <summary>
    /// Завершает сборку записи: применяет адреса, банковские реквизиты,
    /// ограничивает длину значений и проверяет наименование.
    /// </summary>
    /// <param name="реквизиты">Накопитель реквизитов.</param>
    /// <param name="номер">Номер записи (нумерация с единицы).</param>
    /// <param name="метка">Обозначение блока или строки для предупреждений.</param>
    /// <param name="предупреждения">Накопитель предупреждений разбора.</param>
    /// <returns>Запись импорта либо <see langword="null"/>, если запись пропущена.</returns>
    private ImportRecord? ЗавершитьЗапись(
        РеквизитыКонтрагента реквизиты,
        int номер,
        string метка,
        List<string> предупреждения)
    {
        var черновик = реквизиты.Черновик;

        if (реквизиты.Тип is not null)
        {
            черновик.Type = реквизиты.Тип.Value;
        }

        if (черновик.Name.Length == 0
            && (реквизиты.Фамилия.Length > 0 || реквизиты.ИмяОтчество.Length > 0))
        {
            черновик.Name = string.Join(
                ' ',
                new[] { реквизиты.Фамилия, реквизиты.ИмяОтчество, реквизиты.Отчество }
                    .Where(часть => часть.Length > 0));
        }

        ПрименитьАдреса(реквизиты);
        ПрименитьБанковскиеРеквизиты(реквизиты);
        ОграничитьЗначения(реквизиты);

        if (черновик.Name.Length == 0)
        {
            предупреждения.Add($"{метка}: пропущено — не заполнено наименование контрагента.");
            return null;
        }

        return new ImportRecord
        {
            RowNumber = номер,
            Draft = черновик,
            Status = ImportRecordStatus.Unverified,
            Warnings = реквизиты.Предупреждения,
        };
    }

    /// <summary>
    /// Переносит собранные адреса в черновик контрагента: индекс и шесть
    /// адресных строк (ТЗ §3.1.1).
    /// </summary>
    /// <param name="реквизиты">Накопитель реквизитов.</param>
    private void ПрименитьАдреса(РеквизитыКонтрагента реквизиты)
    {
        ПрименитьАдрес(реквизиты, ПолеРеквизита.ПочтовыйАдрес);
        ПрименитьАдрес(реквизиты, ПолеРеквизита.ЮридическийАдрес);
        ПрименитьАдрес(реквизиты, ПолеРеквизита.ФактическийАдрес);
    }

    /// <summary>
    /// Переносит адрес одного вида в черновик контрагента. Индекс извлекается
    /// из составной строки адреса; при его отсутствии запись требует проверки
    /// оператором (ТЗ §8.1, функция 5).
    /// </summary>
    /// <param name="реквизиты">Накопитель реквизитов.</param>
    /// <param name="поле">Вид адреса.</param>
    private void ПрименитьАдрес(РеквизитыКонтрагента реквизиты, ПолеРеквизита поле)
    {
        var данные = АдресПоПолю(реквизиты, поле);
        var черновик = реквизиты.Черновик;

        string zip;
        string[] строки;

        if (данные.Структурированный)
        {
            zip = данные.Zip ?? string.Empty;
            строки = new string[CounterpartyDraft.AddressLineCount];
            строки[1] = данные.Улица ?? string.Empty;
            строки[2] = данные.Дом ?? string.Empty;
            строки[3] = данные.Квартира ?? string.Empty;
            строки[4] = данные.Город ?? string.Empty;
            строки[5] = данные.Регион ?? string.Empty;
        }
        else
        {
            var исходный = данные.Исходный ?? string.Empty;

            if (исходный.Length == 0)
            {
                return;
            }

            var части = исходный.Split(
                AddressParserService.PartSeparator,
                StringSplitOptions.TrimEntries);

            for (var i = 0; i < части.Length; i++)
            {
                if (части[i].Length > MaxValueLength)
                {
                    реквизиты.Предупреждения.Add(
                        $"Адрес: часть {i + 1} длиннее {MaxValueLength} знаков — значение обрезано.");
                }
            }

            var разобранный = _разборАдреса.ParseRawString(исходный, extractZip: true);
            zip = разобранный.Zip;
            строки = разобранный.Lines.ToArray();
        }

        if (zip.Length == 0
            && поле == ПолеРеквизита.ПочтовыйАдрес
            && реквизиты.Индекс is not null)
        {
            zip = реквизиты.Индекс.Trim();
        }

        if (zip.Length == 0)
        {
            черновик.NeedsVerification = true;
        }

        switch (поле)
        {
            case ПолеРеквизита.ПочтовыйАдрес:
                черновик.PostalZip = zip;
                черновик.PostalLines = строки;
                break;

            case ПолеРеквизита.ЮридическийАдрес:
                черновик.LegalZip = zip;
                черновик.LegalLines = строки;
                break;

            default:
                черновик.ActualZip = zip;
                черновик.ActualLines = строки;
                break;
        }
    }

    /// <summary>
    /// Переносит банковские реквизиты (счёт, банк, БИК) в примечание
    /// контрагента: черновик не содержит отдельных банковских полей.
    /// </summary>
    /// <param name="реквизиты">Накопитель реквизитов.</param>
    private static void ПрименитьБанковскиеРеквизиты(РеквизитыКонтрагента реквизиты)
    {
        var части = new List<string>();
        var черновик = реквизиты.Черновик;

        if (!string.IsNullOrWhiteSpace(черновик.Note))
        {
            части.Add(черновик.Note.Trim());
        }

        if (реквизиты.Счет is not null)
        {
            части.Add($"Счёт: {реквизиты.Счет}");
        }

        if (реквизиты.Банк is not null)
        {
            части.Add($"Банк: {реквизиты.Банк}");
        }

        if (реквизиты.БИК is not null)
        {
            части.Add($"БИК: {реквизиты.БИК}");
        }

        черновик.Note = части.Count == 0 ? null : string.Join("; ", части);
    }

    /// <summary>
    /// Ограничивает длину импортируемых значений 255 символами с предупреждением
    /// об усечении (ТЗ §9.7, п. 4).
    /// </summary>
    /// <param name="реквизиты">Накопитель реквизитов.</param>
    private static void ОграничитьЗначения(РеквизитыКонтрагента реквизиты)
    {
        var черновик = реквизиты.Черновик;

        черновик.Name = Ограничить(черновик.Name, "Наименование", реквизиты.Предупреждения) ?? string.Empty;
        черновик.ShortName = Ограничить(черновик.ShortName, "Сокращённое наименование", реквизиты.Предупреждения);
        черновик.Inn = Ограничить(черновик.Inn, "ИНН", реквизиты.Предупреждения);
        черновик.Kpp = Ограничить(черновик.Kpp, "КПП", реквизиты.Предупреждения);
        черновик.Ogrn = Ограничить(черновик.Ogrn, "ОГРН", реквизиты.Предупреждения);
        черновик.Phone = Ограничить(черновик.Phone, "Телефон", реквизиты.Предупреждения);
        черновик.Email = Ограничить(черновик.Email, "Электронная почта", реквизиты.Предупреждения);
        черновик.Note = Ограничить(черновик.Note, "Примечание", реквизиты.Предупреждения);

        черновик.PostalLines = ОграничитьСтроки(черновик.PostalLines, "Почтовый адрес", реквизиты.Предупреждения);
        черновик.LegalLines = ОграничитьСтроки(черновик.LegalLines, "Юридический адрес", реквизиты.Предупреждения);
        черновик.ActualLines = ОграничитьСтроки(черновик.ActualLines, "Фактический адрес", реквизиты.Предупреждения);
    }

    /// <summary>
    /// Обрезает значение до 255 символов, добавляя предупреждение.
    /// </summary>
    /// <param name="значение">Значение поля.</param>
    /// <param name="имяПоля">Название поля для предупреждения.</param>
    /// <param name="предупреждения">Накопитель предупреждений записи.</param>
    /// <returns>Обрезанное значение.</returns>
    private static string? Ограничить(
        string? значение,
        string имяПоля,
        List<string> предупреждения)
    {
        if (значение is null || значение.Length <= MaxValueLength)
        {
            return значение;
        }

        предупреждения.Add(
            $"Поле «{имяПоля}» длиннее {MaxValueLength} знаков — значение обрезано.");

        return значение[..MaxValueLength];
    }

    /// <summary>
    /// Обрезает адресные строки до 255 символов, добавляя предупреждения.
    /// </summary>
    /// <param name="строки">Адресные строки.</param>
    /// <param name="имяПоля">Название адреса для предупреждения.</param>
    /// <param name="предупреждения">Накопитель предупреждений записи.</param>
    /// <returns>Обрезанные адресные строки (ровно шесть).</returns>
    private static string[] ОграничитьСтроки(
        string[] строки,
        string имяПоля,
        List<string> предупреждения)
    {
        var подготовленные = new string[CounterpartyDraft.AddressLineCount];

        for (var i = 0; i < CounterpartyDraft.AddressLineCount; i++)
        {
            var строка = i < строки.Length ? строки[i] ?? string.Empty : string.Empty;

            if (строка.Length > MaxValueLength)
            {
                строка = строка[..MaxValueLength];
                предупреждения.Add(
                    $"{имяПоля}: строка {i + 1} длиннее {MaxValueLength} знаков — значение обрезано.");
            }

            подготовленные[i] = строка;
        }

        return подготовленные;
    }

    /// <summary>
    /// Возвращает реквизит по его имени из файла выгрузки.
    /// </summary>
    /// <param name="ключ">Имя реквизита.</param>
    /// <returns>Реквизит либо <see cref="ПолеРеквизита.Неизвестное"/>.</returns>
    private static ПолеРеквизита ПолеПоКлючу(string? ключ)
    {
        if (string.IsNullOrWhiteSpace(ключ))
        {
            return ПолеРеквизита.Неизвестное;
        }

        return СоответствиеПолей.TryGetValue(НормализоватьКлюч(ключ), out var поле)
            ? поле
            : ПолеРеквизита.Неизвестное;
    }

    /// <summary>
    /// Приводит имя реквизита к нормализованному виду: нижний регистр,
    /// «ё» приравнивается к «е», пробелы и знаки препинания отбрасываются.
    /// </summary>
    /// <param name="значение">Исходное имя реквизита.</param>
    /// <returns>Нормализованное имя реквизита.</returns>
    private static string НормализоватьКлюч(string значение)
    {
        var построитель = new StringBuilder(значение.Length);

        foreach (var символ in значение.ToLowerInvariant())
        {
            if (char.IsWhiteSpace(символ)
                || символ is '_' or '-' or '.' or '(' or ')' or '"' or '\'' or '*' or ':')
            {
                continue;
            }

            построитель.Append(символ == 'ё' ? 'е' : символ);
        }

        return построитель.ToString();
    }

    /// <summary>Реквизиты контрагента, собранные из файла выгрузки.</summary>
    private sealed class РеквизитыКонтрагента
    {
        /// <summary>Черновик контрагента.</summary>
        public CounterpartyDraft Черновик { get; set; } = new();

        /// <summary>Предупреждения записи.</summary>
        public List<string> Предупреждения { get; } = [];

        /// <summary>Фамилия физического лица.</summary>
        public string Фамилия { get; set; } = string.Empty;

        /// <summary>Имя физического лица.</summary>
        public string ИмяОтчество { get; set; } = string.Empty;

        /// <summary>Отчество физического лица.</summary>
