using System.Text.Json;
using Picket302.Shared.Protocol;

namespace Picket302.App.Shared;

/// <summary>
/// Хранилище незавершённых операций рабочего места.
/// </summary>
/// <remarks>
/// <para>
/// Клиентская часть идемпотентности: перед отправкой мутации операция
/// регистрируется вместе с точным телом запроса. Если ответ сервера потерян
/// (разрыв связи после отправки, таймаут), запись остаётся: исход операции
/// неизвестен. Повтор выполняется с прежним идентификатором и прежним телом —
/// служба вернёт прежний результат и не выполнит команду второй раз.
/// </para>
/// <para>
/// Запись удаляется, когда исход стал известен: сервер подтвердил успех,
/// подтвердил отказ либо отклонил повтор с другим содержимым. Изменение
/// состояния памяти выполняется <b>только после подтверждённой записи</b>
/// нового состояния на диск: сбой записи не теряет сведения об операции.
/// Сведения о незавершённой операции хранятся ограниченный срок
/// (см. <see cref="СрокХранения"/>); очистка выполняется контролируемой
/// операцией <see cref="ОчиститьУстаревшие"/> с явным результатом.
/// </para>
/// <para>
/// <b>Fail-closed.</b> Файл истории — единственная копия сведений о
/// незавершённых операциях. Если файл существует, но его нельзя достоверно
/// прочитать (повреждённый JSON, отказ доступа, ошибка чтения), хранилище
/// переходит в заблокированное состояние: новые удалённые мутации
/// не выполняются (они получили бы новый идентификатор и могли бы повторить
/// уже выполненное действие), оператору сообщается, что исход прежних
/// действий неизвестен. Исходный файл при этом не удаляется и не
/// перезаписывается. Восстановление: после устранения причины чтение
/// повторяется автоматически перед каждой операцией
/// (см. <see cref="ПопытатьсяВосстановить"/>); безвозвратно повреждённый
/// файл сбрасывается только явным действием администратора после сверки
/// отправлений на сервере (см. <see cref="ЯвныйСбросПовреждённогоФайла"/>),
/// прежний файл сохраняется с суффиксом для диагностики. В журнал пишутся
/// только факты (повреждён/недоступен), без содержимого JSON.
/// </para>
/// <para>
/// Файл лежит в профиле рабочего места и переживает перезапуск приложения:
/// незавершённая операция прошлой сессии предлагается к повтору при старте.
/// Секретов в файле нет — только идентификатор, имя команды, тело запроса и
/// момент начала.
/// </para>
/// </remarks>
public sealed class PendingOperationsStore
{
    /// <summary>
    /// Незавершённая операция.
    /// </summary>
    /// <param name="Идентификатор">Идентификатор операции.</param>
    /// <param name="Команда">Имя команды службы.</param>
    /// <param name="Тело">Точное тело запроса в виде JSON.</param>
    /// <param name="НачалоUtc">Момент первой отправки (UTC).</param>
    public sealed record НезавершённаяОперация(
        string Идентификатор,
        string Команда,
        string Тело,
        DateTime НачалоUtc);

    /// <summary>Срок хранения сведений о незавершённой операции.</summary>
    public static readonly TimeSpan СрокХранения = TimeSpan.FromDays(7);

    private enum ПричинаБлокировкиФайла
    {
        Нет = 0,

        /// <summary>Файл прочитан, но JSON повреждён: исходное содержимое
        /// неизвестно, восстановление чтением невозможно.</summary>
        Повреждён = 1,

        /// <summary>Файл существует, но чтение не состоялось (отказ доступа,
        /// занят, ошибка ввода-вывода): причина может быть временной.</summary>
        Недоступен = 2,
    }

    private readonly object _блокировка = new();
    private readonly string _путьФайла;
    private readonly Func<DateTime> _часы;
    private readonly Action<string> _журнал;
    private readonly Dictionary<string, НезавершённаяОперация> _операции;
    private ПричинаБлокировкиФайла _причина;

    /// <summary>
    /// Создаёт хранилище над файлом в профиле рабочего места.
    /// </summary>
    /// <remarks>
    /// Конструктор не бросает исключение при нечитаемом файле: приложение
    /// продолжает работу, но хранилище заблокировано
    /// (см. <see cref="Заблокировано"/>) — новые мутации будут отклонены до
    /// восстановления.
    /// </remarks>
    /// <param name="путьФайла">Путь файла хранения.</param>
    /// <param name="часы">
    /// Источник текущего момента; по умолчанию — системные часы (UTC).
    /// </param>
    /// <param name="журнал">Приёмник записей журнала клиента.</param>
    public PendingOperationsStore(
        string путьФайла,
        Func<DateTime>? часы = null,
        Action<string>? журнал = null)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(путьФайла);

        _путьФайла = путьФайла;
        _часы = часы ?? (() => DateTime.UtcNow);
        _журнал = журнал ?? (_ => { });
        _операции = Загрузить();
    }

    /// <summary>
    /// Признак блокировки: файл истории существует, но его нельзя достоверно
    /// прочитать. Новые удалённые мутации отклоняются, исход прежних
    /// действий неизвестен.
    /// </summary>
    public bool Заблокировано => _причина != ПричинаБлокировкиФайла.Нет;

    /// <summary>
    /// Сообщение оператору о причине блокировки (без содержимого JSON).
    /// <see langword="null"/> — блокировки нет.
    /// </summary>
    public string? ПричинаБлокировки => _причина switch
    {
        ПричинаБлокировкиФайла.Повреждён =>
            "История незавершённых операций повреждена: файл нельзя достоверно "
            + "прочитать. Исход прежних действий неизвестен, поэтому новые "
            + "изменения в общей базе заблокированы. Проверьте отправления на "
            + "сервере, затем выполните явный сброс администратором. Файл для "
            + "диагностики сохранён: " + _путьФайла,
        ПричинаБлокировкиФайла.Недоступен =>
            "История незавершённых операций недоступна: файл не читается. "
            + "Исход прежних действий неизвестен, поэтому новые изменения в "
            + "общей базе заблокированы. Устраните причину (доступ к файлу, "
            + "занятость) — блокировка снимется автоматически: " + _путьФайла,
        _ => null,
    };

    /// <summary>
    /// Признак того, что блокировка вызвана повреждением файла: восстановить
    /// чтением невозможно, требуется явный сброс администратора.
    /// </summary>
    public bool ТребуетсяЯвныйСброс => _причина == ПричинаБлокировкиФайла.Повреждён;

    /// <summary>
    /// Незавершённые операции, в порядке регистрации.
    /// </summary>
    /// <remarks>
    /// Чистое чтение памяти: срок хранения проверяется только при загрузке,
    /// восстановлении и в контролируемой операции
    /// <see cref="ОчиститьУстаревшие"/> — построение списка не выполняет
    /// запись и не бросает ошибок ввода-вывода.
    /// </remarks>
    public IReadOnlyList<НезавершённаяОперация> Незавершённые
    {
        get
        {
            lock (_блокировка)
            {
                return _операции.Values
                    .OrderBy(операция => операция.НачалоUtc)
                    .ToList();
            }
        }
    }

    /// <summary>
    /// Регистрирует операцию и возвращает её идентификатор.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Регистрация выполняется до отправки запроса: сбой приложения между
    /// отправкой и получением ответа оставляет запись, и повтор после
    /// перезапуска не создаст дубль.
    /// </para>
    /// <para>
    /// Заблокированное хранилище перед регистрацией пытается восстановиться;
    /// при неудаче мутация не выполняется: её идентификатор был бы новым,
    /// а исход прежних операций неизвестен.
    /// </para>
    /// <para>
    /// Отказ записи на диск не оставляет операцию в памяти: ни диска, ни
    /// памяти, ни отправки — действие не выполнено, оператор получает
    /// понятное сообщение.
    /// </para>
    /// </remarks>
    /// <param name="команда">Имя команды службы.</param>
    /// <param name="телоJson">Тело запроса в виде JSON.</param>
    /// <returns>Идентификатор операции.</returns>
    public string Начать(string команда, string телоJson)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(команда);
        ArgumentException.ThrowIfNullOrWhiteSpace(телоJson);

        lock (_блокировка)
        {
            ПроверитьДоступность();

            var операция = new НезавершённаяОперация(
                Guid.NewGuid().ToString("D"),
                команда,
                телоJson,
                _часы());

            var рабочее = РабочееСостояние();
            рабочее[операция.Идентификатор] = операция;

            // Сначала подтверждённая запись на диск, затем — принятие
            // состояния в память: сбой записи не теряет сведения и не
            // отправляет команду.
            try
            {
                Сохранить(рабочее);
            }
            catch (Exception ошибка) when (ошибка is IOException or UnauthorizedAccessException)
            {
                throw new SharedModeException(
                    SharedErrorCodes.PendingHistoryUnavailable,
                    "Не удалось записать историю незавершённых операций "
                    + "(отказ записи): действие не выполнено, прежние сведения "
                    + "сохранены на диске. Файл: " + _путьФайла);
            }

            Принять(рабочее);

            return операция.Идентификатор;
        }
    }

    /// <summary>
    /// Убирает операцию: её исход стал известен.
    /// </summary>
    /// <remarks>
    /// Операция удаляется из памяти только после подтверждённой записи
    /// нового состояния на диск. При отказе записи сведения остаются и в
    /// памяти, и на диске: повтор такой операции безопасен — служба вернёт
    /// прежний результат.
    /// </remarks>
    /// <param name="идентификатор">Идентификатор операции.</param>
    public void Завершить(string идентификатор)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(идентификатор);

        lock (_блокировка)
        {
            if (!_операции.ContainsKey(идентификатор))
            {
                return;
            }

            var рабочее = РабочееСостояние();
            рабочее.Remove(идентификатор);

            try
            {
                Сохранить(рабочее);
            }
            catch (Exception ошибка) when (ошибка is IOException or UnauthorizedAccessException)
            {
                throw new SharedModeException(
                    SharedErrorCodes.PendingHistoryUnavailable,
                    "Операция выполнена на сервере, но сведения не могли быть "
                    + "удалены из истории (отказ записи): повтор операции безопасен — "
                    + "служба вернёт прежний результат. Файл: " + _путьФайла);
            }

            Принять(рабочее);
        }
    }

    /// <summary>
    /// Читает незавершённую операцию.
    /// </summary>
    /// <param name="идентификатор">Идентификатор операции.</param>
    /// <returns>Операция либо <see langword="null"/>, если её нет.</returns>
    public НезавершённаяОперация? Прочитать(string идентификатор)
    {
        lock (_блокировка)
        {
            return _операции.TryGetValue(идентификатор, out var операция)
                ? операция
                : null;
        }
    }

    /// <summary>
    /// Пытается восстановить хранилище повторным чтением файла: применяется
    /// при временной недоступности (после устранения причины) и перед каждой
    /// операцией в заблокированном состоянии.
    /// </summary>
    /// <returns>
    /// <see langword="true"/>, если блокировки больше нет (файл прочитан или
    /// отсутствует); <see langword="false"/> — хранилище осталось
    /// заблокированным.
    /// </returns>
    public bool ПопытатьсяВосстановить()
    {
        lock (_блокировка)
        {
            if (_причина == ПричинаБлокировкиФайла.Нет)
            {
                return true;
            }

            ПовторитьЧтениеПодБлокировкой();

            return _причина == ПричинаБлокировкиФайла.Нет;
        }
    }

    /// <summary>
    /// Явный сброс безвозвратно повреждённого файла администратором.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Выполняется только после сверки отправлений на сервере: файл
    /// переименовывается с суффиксом «повреждён» (сохраняется для
    /// диагностики), блокировка снимается, хранилище начинает с пустого
    /// состояния. Для повреждения иного рода (недоступность) метод не
    /// применяется — восстановление выполняется чтением.
    /// </para>
    /// </remarks>
    /// <returns>
    /// <see langword="true"/>, если сброс выполнен и блокировка снята.
    /// </returns>
    public bool ЯвныйСбросПовреждённогоФайла()
    {
        lock (_блокировка)
        {
            if (_причина != ПричинаБлокировкиФайла.Повреждён)
            {
                return false;
            }

            try
            {
                File.Move(
                    _путьФайла,
                    _путьФайла + ".повреждён-" + DateTime.UtcNow.Ticks,
                    overwrite: true);
            }
            catch (IOException ошибка)
            {
                _журнал($"Явный сброс повреждённой истории не выполнен "
                    + $"({ошибка.GetType().Name}): файл сохранён на месте.");

                return false;
            }

            _операции.Clear();
            _причина = ПричинаБлокировкиФайла.Нет;

            _журнал("Повреждённая история незавершённых операций сброшена "
                + "явным действием администратора; исходный файл сохранён "
                + "рядом с суффиксом «повреждён».");

            return true;
        }
    }

    /// <summary>
    /// Контролируемая очистка сведений, срок хранения которых истёк.
    /// </summary>
    /// <remarks>
    /// Устаревшие записи удаляются из памяти только после подтверждённой
    /// записи нового состояния на диск; при отказе записи сведения
    /// сохраняются и в памяти, и на диске.
    /// </remarks>
    /// <returns>
    /// Число удалённых записей и признак отказа записи (записи сохранены).
    /// </returns>
    public (int Удалено, bool ОтказЗаписи) ОчиститьУстаревшие()
    {
        lock (_блокировка)
        {
            var рабочее = РабочееСостояние();

            var удалено = УбратьУстаревшие(рабочее);

            if (удалено == 0)
            {
                return (0, false);
            }

            try
            {
                Сохранить(рабочее);
            }
            catch (Exception ошибка) when (ошибка is IOException or UnauthorizedAccessException)
            {
                _журнал($"Не удалось записать очищенную историю незавершённых "
                    + $"операций ({ошибка.GetType().Name}): сведения сохранены "
                    + "в памяти и на диске.");

                return (0, true);
            }

            Принять(рабочее);

            return (удалено, false);
        }
    }

    /// <summary>
    /// Выполняет команду мутации с защитой от дубля при неизвестном исходе.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Операция регистрируется до отправки; её идентификатор и точное тело
    /// сохраняются на всё время попытки. Ответ получен (успех либо
    /// подтверждённый службой отказ) — запись удаляется: исход известен.
    /// Ответ потерян — запись остаётся, оператору сообщается неизвестный
    /// исход, и повтор выполняется с прежними идентификатором и телом.
    /// </para>
    /// <para>
    /// Заблокированное хранилище (нечитаемая история) отклоняет мутацию до
    /// отправки: нельзя начинать действие с новым идентификатором, когда
    /// исход прежних действий неизвестен.
    /// </para>
    /// </remarks>
    /// <typeparam name="TОтвет">Тип ответа команды.</typeparam>
    /// <param name="транспорт">Транспорт клиента совместного режима.</param>
    /// <param name="имяКоманды">Имя команды службы.</param>
    /// <param name="телоJson">Тело запроса в виде JSON.</param>
    /// <param name="токен">Токен отмены.</param>
    /// <returns>Ответ команды.</returns>
    public async Task<TОтвет> ВыполнитьAsync<TОтвет>(
        SharedTransport транспорт,
        string имяКоманды,
        string телоJson,
        CancellationToken токен = default)
    {
        ArgumentNullException.ThrowIfNull(транспорт);

        var идентификатор = Начать(имяКоманды, телоJson);

        try
        {
            var ответ = await транспорт
                .ВыполнитьКомандуJsonAsync<TОтвет>(имяКоманды, телоJson, идентификатор, токен)
                .ConfigureAwait(false);

            ЗавершитьБезопасно(идентификатор);

            return ответ;
        }
        catch (SharedOutcomeUnknownException)
        {
            // Ответ потерян: исход неизвестен, запись остаётся для повтора.
            throw;
        }
        catch (SharedModeException ошибка) when (ошибка.Код == SharedErrorCodes.OperationInProgress)
        {
            // Под этим идентификатором уже выполняется другая попытка: её
            // исход ещё неизвестен, поэтому запись нельзя удалять.
            throw;
        }
        catch (SharedModeException ошибка)
        {
            // Служба ответила содержательным отказом: исход известен.
            ЗавершитьБезопасно(идентификатор);

            throw;
        }
        catch (OperationCanceledException) when (токен.IsCancellationRequested)
        {
            // Отмена во время ожидания: исход неизвестен, запись остаётся.
            throw;
        }
    }

    /// <summary>
    /// Повторяет незавершённую операцию с прежним идентификатором и прежним
    /// телом запроса.
    /// </summary>
    /// <remarks>
    /// Служба либо возвращает прежний результат операции (если первая
    /// попытка дошла), либо выполняет команду первый раз (если не дошла) —
    /// дубля не возникает ни в одном случае. Повтор с телом, отличным от
    /// зарегистрированного, служба отклоняет.
    /// </remarks>
    /// <param name="транспорт">Транспорт клиента совместного режима.</param>
    /// <param name="идентификатор">Идентификатор операции.</param>
    /// <param name="токен">Токен отмены.</param>
    /// <returns>Тело ответа службы в виде JSON.</returns>
    public async Task<string> ПовторитьAsync(
        SharedTransport транспорт,
        string идентификатор,
        CancellationToken токен = default)
    {
        ArgumentNullException.ThrowIfNull(транспорт);

        lock (_блокировка)
        {
            ПроверитьДоступность();
        }

        var запись = Прочитать(идентификатор)
            ?? throw new SharedModeException(
                SharedErrorCodes.NotFound,
                "Незавершённая операция не найдена: возможно, её исход уже стал известен.");

        try
        {
            var ответ = await транспорт
                .ВыполнитьКомандуТекстомAsync(запись.Команда, запись.Тело, запись.Идентификатор, токен)
                .ConfigureAwait(false);

            ЗавершитьБезопасно(идентификатор);

            return ответ;
        }
        catch (SharedOutcomeUnknownException)
        {
            // Ответ снова потерян: исход по-прежнему неизвестен, запись
            // остаётся для следующего повтора.
            throw;
        }
        catch (SharedModeException ошибка) when (ошибка.Код == SharedErrorCodes.OperationInProgress)
        {
            // Команда ещё выполняется на сервере (другая попытка повтора):
            // её исход неизвестен, запись остаётся — следующий повтор вернёт
            // прежний результат либо перехватит устаревшую попытку.
            throw;
        }
        catch (SharedModeException ошибка)
        {
            // Служба ответила содержательным отказом (например, конфликт
            // версии либо повтор под тем же идентификатором с другим
            // содержимым): исход известен, повторять бессмысленно.
            ЗавершитьБезопасно(идентификатор);

            throw;
        }
        catch (OperationCanceledException) when (токен.IsCancellationRequested)
        {
            // Отмена во время ожидания: исход неизвестен, запись остаётся.
            throw;
        }
    }

    /// <summary>
    /// Завершает операцию так, чтобы отказ записи не подменял исход команды:
    /// сведения остаются в памяти и на диске, повтор операции безопасен
    /// (служба вернёт прежний результат).
    /// </summary>
    /// <param name="идентификатор">Идентификатор операции.</param>
    private void ЗавершитьБезопасно(string идентификатор)
    {
        try
        {
            Завершить(идентификатор);
        }
        catch (SharedModeException ошибка) when (ошибка.Код == SharedErrorCodes.PendingHistoryUnavailable)
        {
            _журнал($"Сведения об операции {идентификатор} остались в истории "
                + "(отказ записи): исход команды известен, повтор безопасен.");
        }
    }

    /// <summary>
    /// Отклоняет операцию, если хранилище заблокировано: сначала предпринимается
    /// попытка восстановиться повторным чтением (причина могла быть временной).
    /// </summary>
    private void ПроверитьДоступность()
    {
        if (_причина == ПричинаБлокировкиФайла.Нет)
        {
            return;
        }

        ПовторитьЧтениеПодБлокировкой();

        if (_причина != ПричинаБлокировкиФайла.Нет)
        {
            throw new SharedModeException(
                SharedErrorCodes.PendingHistoryUnavailable,
                ПричинаБлокировки!);
        }
    }

    /// <summary>
    /// Повторяет чтение файла в заблокированном состоянии: успех снимает
    /// блокировку, неудача сохраняет причину.
    /// </summary>
    private void ПовторитьЧтениеПодБлокировкой()
    {
        var восстановленное = Загрузить();

        if (_причина == ПричинаБлокировкиФайла.Нет)
        {
            _операции.Clear();

            foreach (var пара in восстановленное)
            {
                _операции[пара.Key] = пара.Value;
            }
        }
    }

    /// <summary>
    /// Загружает записи из файла.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Отсутствие файла (или каталога) — легальное пустое хранилище.
    /// Существующий, но нечитаемый файл блокирует хранилище: исходный файл
    /// не удаляется и не перезаписывается — в нём может быть единственная
    /// запись операции с неизвестным исходом. В журнал пишется только факт,
    /// без содержимого JSON.
    /// </para>
    /// </remarks>
    /// <returns>Словарь незавершённых операций.</returns>
    private Dictionary<string, НезавершённаяОперация> Загрузить()
    {
        if (!File.Exists(_путьФайла))
        {
            _причина = ПричинаБлокировкиФайла.Нет;

            return new Dictionary<string, НезавершённаяОперация>(StringComparer.Ordinal);
        }

        List<НезавершённаяОперация> записи;

        try
        {
            записи = JsonSerializer.Deserialize<List<НезавершённаяОперация>>(
                File.ReadAllText(_путьФайла),
                SharedJson.Options) ?? [];
        }
        catch (JsonException)
        {
            // Повреждённый файл: исходное содержимое неизвестно, единственный
            // способ безопасного повтора потерян. Файл не удаляется и не
            // перезаписывается: он нужен для диагностики и явного решения
            // администратора; новые мутации блокируются.
            _причина = ПричинаБлокировкиФайла.Повреждён;

            _журнал("Файл незавершённых операций повреждён: хранилище "
                + "заблокировано до явного решения администратора, исходный "
                + "файл сохранён на месте. Содержимое в журнал не выводится.");

            return new Dictionary<string, НезавершённаяОперация>(StringComparer.Ordinal);
        }
        catch (Exception ошибка) when (ошибка is IOException or UnauthorizedAccessException)
        {
            // Файл существует, но не читается (занят, запрет доступа):
            // причина может быть временной — блокировка снимается
            // автоматически после устранения причины.
            _причина = ПричинаБлокировкиФайла.Недоступен;

            _журнал($"Файл незавершённых операций недоступен "
                + $"({ошибка.GetType().Name}): хранилище заблокировано, "
                + "файл сохранён на месте. Содержимое в журнал не выводится.");

            return new Dictionary<string, НезавершённаяОперация>(StringComparer.Ordinal);
        }

        var словарь = new Dictionary<string, НезавершённаяОперация>(StringComparer.Ordinal);

        foreach (var запись in записи)
        {
            if (string.IsNullOrWhiteSpace(запись?.Идентификатор)
                || string.IsNullOrWhiteSpace(запись.Команда)
                || string.IsNullOrWhiteSpace(запись.Тело))
            {
                continue;
            }

            словарь[запись.Идентификатор] = запись;
        }

        УбратьУстаревшие(словарь);

        _причина = ПричинаБлокировкиФайла.Нет;

        return словарь;
    }

    /// <summary>
    /// Удаляет записи, срок хранения которых истёк, в рабочем состоянии.
    /// </summary>
    /// <remarks>
    /// Повтор операции возможен, пока сервер хранит её в журнале
    /// идемпотентности (месяц). Клиентский срок короче: спустя неделю
    /// незавершённая операция считается забытой — исход остаётся
    /// неизвестным, повтор не предлагается.
    /// </remarks>
    /// <param name="операции">Рабочее состояние.</param>
    /// <returns>Число удалённых записей.</returns>
    private int УбратьУстаревшие(Dictionary<string, НезавершённаяОперация> операции)
    {
        var граница = _часы() - СрокХранения;
        var удалено = 0;

        foreach (var ключ in операции
            .Where(пара => пара.Value.НачалоUtc < граница)
            .Select(пара => пара.Key)
            .ToList())
        {
            операции.Remove(ключ);
            удалено++;

            _журнал($"Сведения о незавершённой операции {ключ} удалены: "
                + "истёк срок хранения. Исход операции остался неизвестным.");
        }

        return удалено;
    }

    /// <summary>
    /// Копия текущего состояния для подготовки нового: запись на диск
    /// выполняется только после построения полного нового состояния, а
    /// память меняется только после подтверждённой записи.
    /// </summary>
    /// <returns>Рабочее состояние.</returns>
    private Dictionary<string, НезавершённаяОперация> РабочееСостояние()
        => new(_операции, StringComparer.Ordinal);

    /// <summary>
    /// Заменяет память подготовленным состоянием (после подтверждённой
    /// записи на диск).
    /// </summary>
    /// <param name="состояние">Подтверждённое состояние.</param>
    private void Принять(Dictionary<string, НезавершённаяОперация> состояние)
    {
        _операции.Clear();

        foreach (var пара in состояние)
        {
            _операции[пара.Key] = пара.Value;
        }
    }

    /// <summary>
    /// Атомарно записывает состояние: сначала во временный файл рядом, затем
    /// заменой основного файла.
    /// </summary>
    /// <remarks>
    /// Сбой до замены не уничтожает прежний корректный файл; временный файл
    /// после сбоя удаляется (он не является копией состояния — состояние
    /// остаётся в основном файле) и в любом случае будет перезаписан при
    /// следующей успешной записи.
    /// </remarks>
    /// <param name="операции">Состояние для записи.</param>
    private void Сохранить(Dictionary<string, НезавершённаяОперация> операции)
    {
        var записи = операции.Values
            .OrderBy(операция => операция.НачалоUtc)
            .ToList();

        Directory.CreateDirectory(Path.GetDirectoryName(_путьФайла)!);

        var временный = _путьФайла + ".tmp";

        try
        {
            File.WriteAllText(
                временный,
                JsonSerializer.Serialize(записи, SharedJson.Options),
                new System.Text.UTF8Encoding(encoderShouldEmitUTF8Identifier: false));

            File.Move(временный, _путьФайла, overwrite: true);
        }
        catch (Exception ошибка) when (ошибка is IOException or UnauthorizedAccessException)
        {
            // Прежний файл не тронут. Неполный временный файл — не копия
            // состояния: удаляется, когда это безопасно (основной файл цел).
            try
            {
                if (File.Exists(временный))
                {
                    File.Delete(временный);
                }
            }
            catch (IOException)
            {
                // Временный файл будет перезаписан при следующей успешной
                // записи; состоянии его не читается.
            }

            _журнал($"Запись истории незавершённых операций не выполнена "
                + $"({ошибка.GetType().Name}): прежний файл сохранён.");

            throw;
        }
    }
