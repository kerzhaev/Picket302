using Picket302.Domain.Entities;
using Picket302.Printing.Devices;

namespace Picket302.App.Printing;

/// <summary>
/// Результат сбора писем выбранных рассылок для печати (ТЗ §8.12,
/// функция 156).
/// </summary>
/// <param name="MailIds">Идентификаторы писем к печати.</param>
/// <param name="ПропущенныеРассылки">Наименования пропущенных рассылок.</param>
public sealed record ПисьмаРассылокДляПечати(
    IReadOnlyList<long> MailIds,
    IReadOnlyList<string> ПропущенныеРассылки);

/// <summary>Код завершения запуска печатной операции.</summary>
public enum ПечатьКод
{
    /// <summary>Операция завершена без ошибок.</summary>
    Выполнено = 0,

    /// <summary>Оператор отменил печать (диалог или предпросмотр).</summary>
    Отменено = 1,

    /// <summary>Печать завершилась ошибкой.</summary>
    Ошибка = 2,
}

/// <summary>Итог запуска печатной операции.</summary>
/// <param name="Код">Код завершения.</param>
/// <param name="Сообщение">Текст ошибки для кода <see cref="ПечатьКод.Ошибка"/>.</param>
/// <param name="СообщениеПоказано">
/// Признак того, что сообщение уже показано оператору внутри печатного
/// конвейера; вызывающая сторона не должна дублировать его повторным окном.
/// </param>
public sealed record ПечатьИтог(
    ПечатьКод Код,
    string? Сообщение = null,
    bool СообщениеПоказано = false)
{
    /// <summary>Готовый итог успешной операции.</summary>
    public static ПечатьИтог Выполнено => new(ПечатьКод.Выполнено);

    /// <summary>Готовый итог отмены оператором.</summary>
    public static ПечатьИтог Отменено => new(ПечатьКод.Отменено);

    /// <summary>Общий стабильный текст ошибки без уточнения.</summary>
    public const string ОбщийТекстОшибки = "Печать не выполнена.";

    /// <summary>Стабильный текст ошибки неизменившейся блокировки размера.</summary>
    public const string ТекстБлокировкиРазмера =
        "Печать не выполнена: размер конверта не помещается на выбранный лист.";

    /// <summary>
    /// Преобразует результат печатного конвейера в итог операции. Статус
    /// сессии первичен, наличие текста ошибки — вторично:
    /// <list type="bullet">
    /// <item>ABORTED — всегда отмена оператора: production-текст отмены
    /// («Печать прервана оператором.») ошибкой не считается;</item>
    /// <item>успех разрешён только согласованной парой IsSuccess=true и
    /// SUCCESS;</item>
    /// <item>FAILED — ошибка: с текстом оператора, без текста — общий
    /// стабильный текст (отменой не становится);</item>
    /// <item>BLOCKED_SIZE — ошибка блокировки размера со своим текстом;</item>
    /// <item>несогласованный или неизвестный неуспешный статус — ошибка с
    /// диагностическим текстом; успехом не объявляется никогда.</item>
    /// </list>
    /// Признак <see cref="СообщениеПоказано"/> выставляет вызвавший код,
    /// показавший сообщение оператору.
    /// </summary>
    /// <param name="результат">Результат печатного конвейера.</param>
    /// <returns>Итог операции.</returns>
    public static ПечатьИтог ИзРезультатаКонвейера(global::Picket302.Printing.PrintResult результат)
    {
        ArgumentNullException.ThrowIfNull(результат);

        // Отмена оператора: текст отмены не превращается в ошибку.
        if (Статус(результат, PrintJobStatus.Aborted))
        {
            return Отменено;
        }

        // Успех — только согласованная пара IsSuccess=true и SUCCESS.
        if (результат.IsSuccess && Статус(результат, PrintJobStatus.Success))
        {
            return Выполнено;
        }

        var сообщение = string.IsNullOrWhiteSpace(результат.ErrorMessage)
            ? null
            : результат.ErrorMessage;

        if (Статус(результат, PrintJobStatus.BlockedSize))
        {
            return new ПечатьИтог(ПечатьКод.Ошибка, сообщение ?? ТекстБлокировкиРазмера);
        }

        if (Статус(результат, PrintJobStatus.Failed))
        {
            return new ПечатьИтог(ПечатьКод.Ошибка, сообщение ?? ОбщийТекстОшибки);
        }

        // Неизвестный или несогласованный статус (в том числе IsSuccess=true
        // с неуспешным статусом и IsSuccess=false со статусом SUCCESS) —
        // ошибка с диагностикой, успехом не объявляется.
        return new ПечатьИтог(
            ПечатьКод.Ошибка,
            $"Печать не выполнена: несогласованный результат печатной сессии "
            + $"(IsSuccess={результат.IsSuccess}, Status={результат.Status}).");
    }

    private static bool Статус(global::Picket302.Printing.PrintResult результат, string статус)
        => string.Equals(результат.Status, статус, StringComparison.Ordinal);
}

/// <summary>Код завершения показа предпросмотра.</summary>
public enum ПредпросмотрКод
{
    /// <summary>Предпросмотр построен, оператор разрешил продолжение печати.</summary>
    Разрешено = 0,

    /// <summary>Оператор закрыл предпросмотр без подтверждения.</summary>
    Отменено = 1,

    /// <summary>Документ предпросмотра не построен из-за сбоя.</summary>
    Ошибка = 2,
}

/// <summary>
/// Результат показа предпросмотра: отказ оператора и сбой построения
/// различаются, текст сбоя сохраняется и показывается ровно один раз.
/// </summary>
/// <param name="Код">Код завершения.</param>
/// <param name="Сообщение">Текст сбоя для кода <see cref="ПредпросмотрКод.Ошибка"/>.</param>
/// <param name="СообщениеПоказано">
/// Признак того, что текст сбоя уже показан оператору.
/// </param>
public sealed record ПредпросмотрИтог(
    ПредпросмотрКод Код,
    string? Сообщение = null,
    bool СообщениеПоказано = false)
{
    /// <summary>Готовый итог разрешённого продолжения.</summary>
    public static ПредпросмотрИтог Разрешено => new(ПредпросмотрКод.Разрешено);

    /// <summary>Готовый итог отказа оператора.</summary>
    public static ПредпросмотрИтог Отменено => new(ПредпросмотрКод.Отменено);

    /// <summary>
    /// Итог сбоя построения документа предпросмотра: текст включает
    /// сообщение исключения и показывается вызывающим кодом один раз.
    /// </summary>
    /// <param name="исключение">Исключение построения предпросмотра.</param>
    /// <returns>Итог сбоя.</returns>
    public static ПредпросмотрИтог ИзИсключения(Exception исключение)
    {
        ArgumentNullException.ThrowIfNull(исключение);

        return new ПредпросмотрИтог(
            ПредпросмотрКод.Ошибка,
            $"Не удалось построить предпросмотр: {исключение.Message}");
    }
}

/// <summary>
/// Итог сценария печати выбранных рассылок: что собрано, что пропущено и
/// чем закончился запуск печатной операции.
/// </summary>
/// <param name="НичегоНеВыбрано">Ни одна рассылка не передана.</param>
/// <param name="ПропущенныеРассылки">Пустые и отсутствующие рассылки.</param>
/// <param name="Письма">Собранные письма (переданы в печать).</param>
/// <param name="ПечатьЗапущена">Печатная операция была запущена.</param>
/// <param name="ЗавершёноУспешно">Операция завершена кодом «Выполнено».</param>
/// <param name="Отменено">Оператор отменил печать.</param>
/// <param name="Ошибка">Текст ошибки печати, если она произошла.</param>
/// <param name="ОшибкаСообщенаОператору">
/// Признак того, что текст ошибки уже показан оператору внутри конвейера —
/// оболочка не должна дублировать его повторным окном.
/// </param>
/// <param name="ПредупреждениеБезПринтера">
/// Штатное предупреждение об отсутствии принтера по умолчанию.
/// </param>
public sealed record ИтогПечатиРассылок(
    bool НичегоНеВыбрано,
    IReadOnlyList<string> ПропущенныеРассылки,
    IReadOnlyList<long> Письма,
    bool ПечатьЗапущена,
    bool ЗавершёноУспешно,
    bool Отменено,
    string? Ошибка,
    bool ОшибкаСообщенаОператору,
    string? ПредупреждениеБезПринтера);

/// <summary>
/// Сценарий печати выбранных рассылок (ТЗ §8.12, функция 156): сбор писем,
/// проверка принтера и запуск печатной операции — без обращения к элементам
/// интерфейса. Сам запуск передаётся делегатом, поэтому сценарий проверяется
/// в тестах без реального принтера и диалогов; рабочая оболочка передаёт
/// настоящий конвейер печати.
/// </summary>
public static class DistributionPrintScenario
{
    /// <summary>
    /// Выполняет сценарий печати выбранных рассылок.
    /// </summary>
    /// <param name="состав">Состав приложения.</param>
    /// <param name="идентификаторыРассылок">Идентификаторы выбранных рассылок.</param>
    /// <param name="печать">
    /// Запуск печатной операции по письмам; возвращает итог операции.
    /// </param>
    /// <param name="принтерПоУмолчанию">
    /// Имя принтера по умолчанию; по умолчанию берётся из службы принтеров.
    /// </param>
    /// <param name="статус">Приёмник сообщений строки состояния.</param>
    /// <returns>Итог сценария.</returns>
    public static async Task<ИтогПечатиРассылок> ВыполнитьAsync(
        AppServices состав,
        IReadOnlyList<long> идентификаторыРассылок,
        Func<IReadOnlyList<long>, Task<ПечатьИтог>> печать,
        Func<string?>? принтерПоУмолчанию = null,
        Action<string>? статус = null)
    {
        ArgumentNullException.ThrowIfNull(состав);
        ArgumentNullException.ThrowIfNull(идентификаторыРассылок);
        ArgumentNullException.ThrowIfNull(печать);

        if (идентификаторыРассылок.Count == 0)
        {
            return new ИтогПечатиРассылок(
                НичегоНеВыбрано: true,
                ПропущенныеРассылки: [],
                Письма: [],
                ПечатьЗапущена: false,
                ЗавершёноУспешно: false,
                Отменено: false,
                Ошибка: null,
                ОшибкаСообщенаОператору: false,
                ПредупреждениеБезПринтера: null);
        }

        // ТЗ §8.6, функция 78: без принтера по умолчанию печать блокируется.
        var выборПринтера = принтерПоУмолчанию
            ?? (() => состав.СлужбаПринтеров.GetDefaultPrinter()?.Name);
        var безПринтера = выборПринтера() is null
            ? PrinterManager.NoDefaultPrinterMessage
            : null;

        if (безПринтера is not null)
        {
            return new ИтогПечатиРассылок(
                НичегоНеВыбрано: false,
                ПропущенныеРассылки: [],
                Письма: [],
                ПечатьЗапущена: false,
                ЗавершёноУспешно: false,
                Отменено: false,
                Ошибка: null,
                ОшибкаСообщенаОператору: false,
                ПредупреждениеБезПринтера: безПринтера);
        }

        var сборка = await СобратьПисьмаРассылокAsync(состав, идентификаторыРассылок)
            .ConfigureAwait(true);

        if (сборка.MailIds.Count == 0)
        {
            return new ИтогПечатиРассылок(
                НичегоНеВыбрано: false,
                ПропущенныеРассылки: сборка.ПропущенныеРассылки,
                Письма: [],
                ПечатьЗапущена: false,
                ЗавершёноУспешно: false,
                Отменено: false,
                Ошибка: null,
                ОшибкаСообщенаОператору: false,
                ПредупреждениеБезПринтера: null);
        }

        статус?.Invoke($"Печать рассылок: отправлений {сборка.MailIds.Count}…");

        ПечатьИтог итог;

        try
        {
            итог = await печать(сборка.MailIds).ConfigureAwait(true);
        }
        finally
        {
            статус?.Invoke(string.Empty);
        }

        return итог.Код switch
        {
            ПечатьКод.Выполнено => new ИтогПечатиРассылок(
                false, сборка.ПропущенныеРассылки, сборка.MailIds,
                ПечатьЗапущена: true, ЗавершёноУспешно: true,
                Отменено: false, Ошибка: null, ОшибкаСообщенаОператору: false,
                ПредупреждениеБезПринтера: null),

            ПечатьКод.Отменено => new ИтогПечатиРассылок(
                false, сборка.ПропущенныеРассылки, сборка.MailIds,
                ПечатьЗапущена: true, ЗавершёноУспешно: false,
                Отменено: true, Ошибка: null, ОшибкаСообщенаОператору: false,
                ПредупреждениеБезПринтера: null),

            _ => new ИтогПечатиРассылок(
                false, сборка.ПропущенныеРассылки, сборка.MailIds,
                ПечатьЗапущена: true, ЗавершёноУспешно: false,
                Отменено: false,
                Ошибка: итог.Сообщение ?? "Печать не выполнена.",
                ОшибкаСообщенаОператору: итог.СообщениеПоказано,
                ПредупреждениеБезПринтера: null),
        };
    }

    /// <summary>
    /// Собирает письма выбранных рассылок для печати (ТЗ §8.12, функция 156):
    /// отсутствующие и пустые рассылки пропускаются и перечисляются по
    /// имени, печать идёт только по готовым письмам. Письмо принадлежит
    /// одной рассылке, поэтому дубликаты идентификаторов невозможны.
    /// </summary>
    /// <param name="состав">Состав приложения.</param>
    /// <param name="идентификаторы">Идентификаторы рассылок.</param>
    /// <returns>Идентификаторы писем и перечень пропущенных рассылок.</returns>
    public static async Task<ПисьмаРассылокДляПечати> СобратьПисьмаРассылокAsync(
        AppServices состав,
        IReadOnlyList<long> идентификаторы)
    {
        ArgumentNullException.ThrowIfNull(состав);
        ArgumentNullException.ThrowIfNull(идентификаторы);

        var письма = new List<long>();
        var пропущенные = new List<string>();

        foreach (var идентификатор in идентификаторы)
        {
            var рассылка = await состав.Рассылки
                .GetByIdAsync(идентификатор)
                .ConfigureAwait(true);

            if (рассылка is null)
            {
                пропущенные.Add($"№{идентификатор} (не найдена)");
                continue;
            }

            var письмаРассылки = await состав.Письма
                .GetByDistributionAsync(идентификатор)
                .ConfigureAwait(true);

            if (письмаРассылки.Count == 0)
            {
                пропущенные.Add($"«{рассылка.Name}» (нет писем)");
                continue;
            }

            письма.AddRange(письмаРассылки.Select(письмо => письмо.Id));
        }

        return new ПисьмаРассылокДляПечати(письма, пропущенные);
    }
}
