namespace Picket302.Domain.Licensing;

/// <summary>
/// Операция, ограничиваемая лимитами пробного периода (ТЗ §8.10, функция 119:
/// «создание записей и печать партий блокируются с понятным сообщением и
/// оставшимися днями»).
/// </summary>
public enum LicenseOperation
{
    /// <summary>Создание записей: карточки контрагентов, отправления, импорт данных.</summary>
    СозданиеЗаписей = 0,

    /// <summary>Печать партий конвертов (F7).</summary>
    ПечатьПартий = 1,
}

/// <summary>
/// Решение ворот лицензии: разрешена ли операция и что показать оператору
/// (ТЗ §8.10, функция 119).
/// </summary>
/// <param name="Разрешено">Признак разрешения операции.</param>
/// <param name="Сообщение">Текст сообщения для оператора; при разрешении — пустой.</param>
/// <param name="ОсталосьДней">Число оставшихся дней срока пробного периода.</param>
/// <param name="Состояние">Состояние лицензии на момент проверки.</param>
public sealed record LicenseGateDecision(
    bool Разрешено,
    string Сообщение,
    int ОсталосьДней,
    LicenseState Состояние)
{
    /// <summary>Формирует разрешающее решение.</summary>
    /// <param name="состояние">Состояние лицензии.</param>
    /// <param name="осталосьДней">Число оставшихся дней срока.</param>
    /// <returns>Разрешающее решение.</returns>
    public static LicenseGateDecision Разрешить(LicenseState состояние, int осталосьДней)
        => new(true, string.Empty, осталосьДней, состояние);

    /// <summary>Формирует запрещающее решение с сообщением для оператора.</summary>
    /// <param name="состояние">Состояние лицензии.</param>
    /// <param name="осталосьДней">Число оставшихся дней срока.</param>
    /// <param name="сообщение">Текст сообщения для оператора.</param>
    /// <returns>Запрещающее решение.</returns>
    public static LicenseGateDecision Запретить(LicenseState состояние, int осталосьДней, string сообщение)
        => new(false, сообщение, осталосьДней, состояние);
}

/// <summary>
/// Ворота лицензии — единая точка проверки ограничений пробного периода
/// (ТЗ §8.10, функция 119: «состояние лицензии — один автомат, проверки
/// представления читают это состояние»).
/// </summary>
/// <remarks>
/// Интерфейс объявлен в доменном слое, чтобы и прикладные службы, и слой
/// печати проверяли один и тот же статус, не создавая циклических зависимостей
/// между проектами.
/// </remarks>
public interface ILicenseGate
{
    /// <summary>Текущий статус лицензии.</summary>
    LicenseStatus ТекущийСтатус { get; }

    /// <summary>Проверяет возможность выполнить операцию.</summary>
    /// <param name="операция">Проверяемая операция.</param>
    /// <returns>Решение о допустимости операции.</returns>
    LicenseGateDecision Проверить(LicenseOperation операция);
}

/// <summary>
/// Исключение лимитов лицензии: операция не выполнена, потому что срок
/// пробного периода истёк либо лимит объёма исчерпан (ТЗ §8.10, функция 119).
/// </summary>
public sealed class LicenseLimitExceededException : InvalidOperationException
{
    /// <summary>Создаёт исключение с текстом для оператора.</summary>
    /// <param name="message">Текст сообщения для оператора.</param>
    public LicenseLimitExceededException(string message)
        : base(message)
    {
    }
}
