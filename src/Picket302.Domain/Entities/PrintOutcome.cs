namespace Picket302.Domain.Entities;

/// <summary>
/// Исход печатной операции (ТЗ §3.1.7, колонка <c>print_history.outcome</c>).
/// </summary>
/// <remarks>
/// <para>
/// Значения различают четыре состояния, которые нельзя смешивать:
/// «подготовлено» (данные собраны, задание в спулер не передавалось),
/// «передано локальному спулеру» (задание принято спулером рабочего места),
/// «ошибка» и «неизвестный исход после обрыва» (состояние установить
/// нельзя).
/// </para>
/// <para>
/// Подтверждение спулера не равно физически напечатанному конверту: исход
/// описывает состояние задания у локального спулера, а не наличие листа в
/// лотке принтера.
/// </para>
/// <para>
/// Перечисление живёт в доменном слое, потому что им пользуется и служба, и
/// оболочка, а контрактный слой совместного режима переводит его в свой тип
/// (<c>PrintEventOutcome</c>) один-в-один.
/// </para>
/// </remarks>
public enum PrintOutcome
{
    /// <summary>
    /// Подготовлено: данные печати собраны, задание в локальный спулер не
    /// передавалось. Конверт не напечатан.
    /// </summary>
    Prepared = 0,

    /// <summary>
    /// Передано локальному спулеру рабочего места: задание принято спулером.
    /// </summary>
    Spooled = 1,

    /// <summary>
    /// Ошибка печати: задание не принято спулером, конверт не напечатан.
    /// </summary>
    Error = 2,

    /// <summary>
    /// Неизвестный исход после обрыва связи: установить состояние нельзя.
    /// </summary>
    /// <remarks>
    /// Исход применяется к записи в общем журнале, когда сама запись не
    /// подтверждена: сервер мог как выполнить, так и не выполнить команду.
    /// Повтор такой записи выполняется с прежним идентификатором операции и
    /// не приводит к повторной физической печати.
    /// </remarks>
    Unknown = 3,
}
