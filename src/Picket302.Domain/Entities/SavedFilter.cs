using Picket302.Domain.Contracts;

namespace Picket302.Domain.Entities;

/// <summary>
/// Сохранённый пользовательский фильтр адресной книги
/// (ТЗ §8.1, функция 9: «Фильтры и сортировка по любой колонке; сохранённые
/// пользовательские фильтры»).
/// </summary>
/// <remarks>
/// Фильтр хранится в файле настроек интерфейса вместе с прочими настройками
/// отображения. Имя фильтра уникально в пределах набора: сохранение под
/// существующим именем обновляет фильтр, а не создаёт второй.
/// </remarks>
public sealed record SavedFilter
{
    /// <summary>Имя фильтра — ключ сохранения и обращения к фильтру.</summary>
    public string Name { get; init; } = string.Empty;

    /// <summary>
    /// Условия отбора и сортировки, сохранённые вместе с фильтром.
    /// </summary>
    public FilterCriteria Criteria { get; init; } = new();
}
