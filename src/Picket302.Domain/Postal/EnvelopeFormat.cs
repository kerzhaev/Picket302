namespace Picket302.Domain.Postal;

/// <summary>
/// Базовый формат конверта (ТЗ §8.4, функция 42: <c>GetGeometry(EnvelopeFormat format,
/// EnvelopeOrientation orientation)</c>; §8.5, функция 149: «Список форматов строится
/// из таблицы форматов стандарта (включая варианты "/О" с окном)»).
/// </summary>
/// <remarks>
/// Перечисление содержит базовые обозначения ISO 269, применяемые ГОСТ Р 51506-99.
/// Разновидности «/О» (с окном) в перечисление не входят: справочник
/// <see cref="EnvelopeFormatCatalog"/> хранит их как отдельные записи данных.
/// </remarks>
public enum EnvelopeFormat
{
    /// <summary>С6 — 114×162 мм (ГОСТ Р 51506-99, таблица 1).</summary>
    C6 = 0,

    /// <summary>DL — 110×220 мм (европейский стандарт Е65).</summary>
    DL = 1,

    /// <summary>С5 — 162×229 мм.</summary>
    C5 = 2,

    /// <summary>С4 — 229×324 мм.</summary>
    C4 = 3,

    /// <summary>С3 — 324×458 мм.</summary>
    C3 = 4,

    /// <summary>В4 — 250×353 мм.</summary>
    B4 = 5,

    /// <summary>Е65 — 110×220 мм (европейский стандарт).</summary>
    E65 = 6,

    /// <summary>Е4 — 220×312 мм (формат для вложений A4).</summary>
    E4 = 7,

    /// <summary>К5 — 145×215 мм (нестандартный формат упаковки).</summary>
    K5 = 8,

    /// <summary>К6 — 125×125 мм (нестандартный формат упаковки).</summary>
    K6 = 9,

    /// <summary>К8 — 150×150 мм (нестандартный формат упаковки).</summary>
    K8 = 10,

    /// <summary>К65 — 125×190 мм (нестандартный формат упаковки).</summary>
    K65 = 11,
}

/// <summary>
/// Тип конверта по месту расположения закрывающего клапана (ГОСТ Р 51506-99, п. 4.1.3).
/// </summary>
public enum EnvelopeFlapType
{
    /// <summary>
    /// Б — конверт с боковым расположением клапана: сгиб клапана совпадает с боковым
    /// (коротким) левым краем конверта относительно его лицевой стороны.
    /// </summary>
    Side = 0,

    /// <summary>
    /// В — конверт с верхним расположением клапана: сгиб клапана совпадает с верхним
    /// (длинным) краем конверта относительно его лицевой стороны.
    /// </summary>
    Top = 1,

    /// <summary>
    /// В/Б — конверт допускает оба типа расположения клапана (ГОСТ Р 51506-99,
    /// таблица 2: форматы С5, С4, В4).
    /// </summary>
    SideOrTop = 2,
}

/// <summary>
/// Территория хождения конверта (ГОСТ Р 51506-99, п. 4.1.5).
/// </summary>
public enum EnvelopeTerritory
{
    /// <summary>
    /// Вн — конверт для внутренних почтовых отправлений (в пределах Российской Федерации);
    /// оформляется шестизначным кодовым штампом.
    /// </summary>
    Domestic = 0,

    /// <summary>
    /// Мн — конверт для международных почтовых отправлений; оформляется трёхзначным
    /// кодовым штампом с индексом «555» и подсказкой «Адрес отправителя».
    /// </summary>
    International = 1,
}
