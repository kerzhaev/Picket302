namespace Picket302.Domain.Common;

/// <summary>
/// Содержимое пакета шаблона недоступно: получить версию, с которой связана
/// строка шаблона, не удалось.
/// </summary>
/// <remarks>
/// <para>
/// Исключение означает, что печать или предпросмотр не должны выполняться с
/// содержимым, которое не совпадает с версией пакета: молчаливый откат на
/// прежний или на иной макет дал бы напечатанный конверт, отличный от
/// ожидаемого.
/// </para>
/// <para>
/// Исключение живёт в доменном слое: печатный конвейер не знает о совместном
/// режиме, но обязан отказать в печати понятным сообщением, а не
/// продолжить работу с неполными данными.
/// </para>
/// </remarks>
public sealed class TemplatePackageUnavailableException : Exception
{
    /// <summary>
    /// Создаёт исключение.
    /// </summary>
    /// <param name="message">Пояснение для оператора.</param>
    public TemplatePackageUnavailableException(string message)
        : base(message)
    {
    }
}
