namespace Picket302.Domain.Common;

/// <summary>
/// Исход операции неизвестен: запрос мог быть выполнен, а мог и не быть.
/// </summary>
/// <remarks>
/// <para>
/// Исключение означает, что установить состояние нельзя: связь прервалась
/// после передачи запроса, но до получения ответа. Повтор такого запроса
/// выполняется с прежним идентификатором операции — сервер возвращает
/// прежний результат и не создаёт дубль.
/// </para>
/// <para>
/// Исключение живёт в доменном слое: печатный конвейер не знает о совместном
/// режиме, но обязан различать «операция не выполнена» и «исход неизвестен».
/// Различие это важно для печати: неизвестный исход записи сессии не должен
/// выглядеть как «конверты не напечатаны», и он не должен приводить к
/// повторной физической печати.
/// </para>
/// </remarks>
public sealed class OutcomeUnknownException : Exception
{
    /// <summary>
    /// Создаёт исключение.
    /// </summary>
    /// <param name="message">Пояснение для оператора.</param>
    public OutcomeUnknownException(string message)
        : base(message)
    {
    }
}
