-- Описание: привязка строки шаблона к версии пакета .lbk и идентификатор операции в журнале печати

-- Строка шаблона в совместном режиме хранит метаданные, а содержимое макета
-- лежит в управляемом пакете .lbk на сервере. Без явной привязки к пакету
-- рабочее место не может получить содержимое макета: путь к файлу на сервере
-- клиенту не передаётся, а имя файла в строке шаблона для другого
-- компьютера ничего не значит.
--
-- Привязка состоит из трёх величин: идентификатор пакета, версия и
-- SHA-256 содержимого этой версии. Клиент запрашивает именно эту версию и
-- сверяет отпечаток, поэтому после смены версии пакета старое содержимое из
-- кэша не используется. Пустые значения означают, что шаблон не связан с
-- файловым пакетом (например, в одиночном режиме).
ALTER TABLE print_templates ADD COLUMN package_id TEXT NULL;
ALTER TABLE print_templates ADD COLUMN package_version INTEGER NULL;
ALTER TABLE print_templates ADD COLUMN package_hash TEXT NULL;

-- Идентификатор операции печатной записи в общем журнале: безопасная
-- ссылка, по которой повтор записи после обрыва связи опознаётся как
-- повтор той же операции, а не как новая печать. Секретов и иных
-- персональных данных колонка не содержит.
ALTER TABLE print_history ADD COLUMN operation_id TEXT NULL;

CREATE INDEX IF NOT EXISTS idx_print_history_operation ON print_history (operation_id);
