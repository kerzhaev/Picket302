-- Описание: поворот текста в поле бланка (градусы)

-- На конвертах Почты России адрес печатается вертикальной колонкой, снизу
-- вверх: так напечатаны рамки на бланке. Макеты исходной программы хранят
-- этот поворот, и без него адрес лёг бы горизонтально мимо рамок.
--
-- Значение по умолчанию 0 — поворот отсутствует, прежнее поведение
-- сохраняется.

ALTER TABLE blank_fields ADD COLUMN rotation INTEGER NOT NULL DEFAULT 0;
