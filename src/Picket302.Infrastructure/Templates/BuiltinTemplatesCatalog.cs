    private static CustomBlank Заготовка(string наименование, decimal ширина, decimal высота, int страницы, string страна = "RUS")
    {
        var бланк = new CustomBlank
        {
            Name = наименование,
            Country = страна,
            StandardLayout = true,
            Geometry = new BlankGeometry
            {
                WidthMm = ширина,
                HeightMm = высота,
                Orientation = ширина > высота ? BlankOrientation.Landscape : BlankOrientation.Portrait,
                BleedMm = 0.0m,
                CropMarks = false,
            },
        };

        for (var номер = 1; номер <= страницы; номер++)
        {
            бланк.Pages.Add(new BlankPage { Number = номер });
        }

        return бланк;
    }
