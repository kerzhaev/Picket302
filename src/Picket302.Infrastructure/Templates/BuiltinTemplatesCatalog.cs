/// <summary>
/// Виды восьми встроенных эталонных бланков (ТЗ §8.3, функция 36).
/// </summary>
public enum BuiltinFormType
{
    /// <summary>Почтовый перевод (электронный) ф.112эп.</summary>
    Form112ep = 0,

    /// <summary>Почтовый перевод (электронный) ф.112э.</summary>
    Form112e = 1,

    /// <summary>Почтовый перевод (электронный) ф.112эф.</summary>
    Form112ef = 2,

    /// <summary>Почтовый перевод (электронный) ф.112эю.</summary>
    Form112eyu = 3,

    /// <summary>Комбинированный бланк перевода наложенного платежа ф.117+ф.113.</summary>
    Form117and113 = 4,

    /// <summary>Сопроводительный адрес к посылке ф.116.</summary>
    Form116 = 5,

    /// <summary>Уведомление о вручении ф.119 (2011).</summary>
    Form119_2011 = 6,

    /// <summary>Конверт C5 (2012).</summary>
    EnvelopeC5_2012 = 7,
}

/// <summary>
/// Потоковая раскладка полей бланка по словарю полей встроенных форм
/// (EVIDENCE/blank_field_vocabulary.txt): колонки заполняются сверху вниз,
/// следующая колонка начинается, когда высота формы исчерпана. Поля
/// машиночитаемого индекса размещаются в нижней полосе страницы, и текстовый
/// поток не заходит в неё — раскладка выполняется без пересечений AABB.
/// </summary>
internal static class BlankFieldsBuilder
{
    /// <summary>Отступ от края формы, мм.</summary>
    public const decimal Отступ = 8m;

    /// <summary>Зазор между полями по вертикали, мм.</summary>
    public const decimal Зазор = 1m;

    /// <summary>Зазор между колонками, мм.</summary>
    public const decimal Межколонник = 4m;

    /// <summary>Высота однострочного поля, мм (кегль 3–5 пт по словарю форм).</summary>
    public const decimal ВысотаСтроки = 5m;

    /// <summary>Высота многострочного адресного поля (5 строк), мм.</summary>
    public const decimal ВысотаАдреса = 18m;

    /// <summary>Минимальная ширина колонки, мм.</summary>
    public const decimal МинКолонка = 24m;

    /// <summary>Максимальная ширина колонки, мм.</summary>
    public const decimal МаксКолонка = 60m;

    /// <summary>Ширина поля кодового штампа, мм.</summary>
    public const decimal ШиринаШтампа = 5 * 5.4m + 3.7m;

    /// <summary>Высота поля кодового штампа, мм.</summary>
    public const decimal ВысотаШтампа = 5.5m;

    /// <summary>
    /// Раскладывает перечень наименований полей по колонкам страницы без
    /// пересечений AABB; курсор продолжает позицию после последнего текстового
    /// поля страницы, поэтому несколько вызовов продолжают одну раскладку.
    /// Поля кодового штампа, уже размещённые на странице, занимают нижнюю
    /// полосу — текстовый поток в неё не заходит.
    /// </summary>
    /// <param name="страница">Страница бланка.</param>
    /// <param name="наименования">Наименования полей.</param>
    /// <param name="ширина">Ширина формы, мм.</param>
    /// <param name="высота">Высота формы, мм.</param>
    /// <param name="резервСправа">Полоса справа, зарезервированная под объекты, мм.</param>
    public static void Разложить(
        BlankPage страница,
        IEnumerable<string> наименования,
        decimal ширина,
        decimal высота,
        decimal резервСправа = 0m)
    {
        ArgumentNullException.ThrowIfNull(страница);

        var имена = наименования.ToList();

        if (имена.Count == 0)
        {
            return;
        }

        var естьШтампы = страница.Fields.Any(поле => поле.Kind == BlankFieldKinds.PostIndex);

        // Нижняя полоса под кодовые штампы: текстовый поток не заходит в неё.
        var полосаШтампов = естьШтампы ? ВысотаШтампа + 3m : 0m;

        var доступнаяШирина = ширина - Отступ - резервСправа - Отступ;
        var нижняяГраница = высота - Отступ - полосаШтампов;
        var полезнаяВысота = нижняяГраница - Отступ;

        // Потребная длина одной колонки и число колонок.
        var потребность = имена.Sum(наименование =>
            ЯвляетсяАдресным(наименование) ? ВысотаАдреса + Зазор : ВысотаСтроки + Зазор);

        var колонок = Math.Max(1, (int)Math.Ceiling(потребность / полезнаяВысота));

        // Колонок не может быть больше, чем вмещает ширина.
        var максимумКолонок = Math.Max(1, (int)((доступнаяШирина + Межколонник) / (МинКолонка + Межколонник)));

        if (колонок > максимумКолонок)
        {
            колонок = максимумКолонок;
        }

        var ширинаКолонки = Math.Min(
            МаксКолонка,
            Math.Max(
                МинКолонка,
                (доступнаяШирина - (колонок - 1) * Межколонник) / колонок));

        var (x, y) = НачальныйКурсор(страница);

        foreach (var наименование in имена)
        {
            var адресное = ЯвляетсяАдресным(наименование);
            var высотаПоля = адресное ? ВысотаАдреса : ВысотаСтроки;

            if (y + высотаПоля > нижняяГраница)
            {
                x += ширинаКолонки + Межколонник;
                y = Отступ;
            }

            страница.Fields.Add(new BlankFieldSpec
            {
                Name = наименование,
                Kind = BlankFieldKinds.Text,
                Bounds = new BlankBounds
                {
                    XMm = x,
                    YMm = y,
                    WidthMm = ширинаКолонки,
                    HeightMm = высотаПоля,
                },
                WordWrap = true,
                MaxLines = адресное ? 5 : 1,
                // Поля реквизитов, заполняемые только вручную, выводятся
                // на экране и отсекаются при печати (ТЗ §7.5); адресные
                // поля данных получателя печатаются.
                Printable = адресное,
            });

            y += высотаПоля + Зазор;
        }
    }

    /// <summary>
    /// Размещает поля машиночитаемого индекса в нижней полосе страницы —
    /// справа налево; текстовый поток резервирует эту полосу. Вызывается
    /// до <see cref="Разложить"/>.
    /// </summary>
    /// <param name="страница">Страница.</param>
    /// <param name="штампы">Пары «наименование поля — признак печати».</param>
    /// <param name="ширина">Ширина формы, мм.</param>
    /// <param name="высота">Высота формы, мм.</param>
    public static void ШтампыВПолосу(
        BlankPage страница,
        IReadOnlyList<(string Наименование, bool Печатается)> штампы,
        decimal ширина,
        decimal высота)
    {
        ArgumentNullException.ThrowIfNull(страница);
        ArgumentNullException.ThrowIfNull(штампы);

        var y = высота - Отступ - ВысотаШтампа;

        foreach (var (наименование, печатается) in штампы)
        {
            var номер = страница.Fields.Count(поле => поле.Kind == BlankFieldKinds.PostIndex);
            var x = ширина - Отступ - (номер * (ШиринаШтампа + 2m)) - ШиринаШтампа;

            страница.Fields.Add(new BlankFieldSpec
            {
                Name = наименование,
                Kind = BlankFieldKinds.PostIndex,
                Bounds = new BlankBounds
                {
                    XMm = x,
                    YMm = y,
                    WidthMm = ШиринаШтампа,
                    HeightMm = ВысотаШтампа,
                },
                Printable = печатается,
                PostIndex = new BlankPostIndexSpec(),
            });
        }
    }

    /// <summary>
    /// Размещает поля кодового штампа в НИЖНЕЙ ЛЕВОй полосе (ГОСТ Р 51506-99:
    /// сетка индекса получателя — в левом нижнем углу), слева направо.
    /// </summary>
    public static void ШтампыСлеваВПолосу(
        BlankPage страница,
        IReadOnlyList<(string Наименование, bool Печатается)> штампы,
        decimal ширина,
        decimal высота)
    {
        ArgumentNullException.ThrowIfNull(страница);
        ArgumentNullException.ThrowIfNull(штампы);

        var y = высота - Отступ - ВысотаШтампа;

        foreach (var (наименование, печатается) in штампы)
        {
            var номер = страница.Fields.Count(поле => поле.Kind == BlankFieldKinds.PostIndex);
            var x = Отступ + (номер * (ШиринаШтампа + 2m));

            страница.Fields.Add(new BlankFieldSpec
            {
                Name = наименование,
                Kind = BlankFieldKinds.PostIndex,
                Bounds = new BlankBounds
                {
                    XMm = x,
                    YMm = y,
                    WidthMm = ШиринаШтампа,
                    HeightMm = ВысотаШтампа,
                },
                Printable = печатается,
                PostIndex = new BlankPostIndexSpec(),
            });
        }
    }

    /// <summary>
    /// Раскладка стандартного конверта по зонам ГОСТ Р 51506-99:
    /// адрес отправителя — левый верхний угол; адрес получателя — правая
    /// нижняя часть; кодовый штамп индекса получателя — левый нижний угол;
    /// зона марки/франкирования (74×40 мм, правый верхний угол) остаётся
    /// свободной от полей. Вспомогательные реквизиты — левой колонкой ниже
    /// адреса отправителя, не заходя в зону марки и полосу индекса.
    /// </summary>
    /// <param name="страница">Страница бланка.</param>
    /// <param name="ширина">Ширина конверта, мм.</param>
    /// <param name="высота">Высота конверта, мм.</param>
    /// <param name="вспомогательные">Однострочные реквизиты левой колонки.</param>
    public static void РазложитьКонвертПоГОСТ(
        BlankPage страница,
        decimal ширина,
        decimal высота,
        IReadOnlyList<string> вспомогательные)
    {
        ArgumentNullException.ThrowIfNull(страница);
        ArgumentNullException.ThrowIfNull(вспомогательные);

        var ширинаКолонки = Math.Min(МаксКолонка, Math.Max(МинКолонка, ширина * 0.42m));
        var праваяКолонка = Math.Min(МаксКолонка, Math.Max(МинКолонка, ширина * 0.45m));

        // Отправитель — левый верхний угол.
        var yОтправителя = Отступ;
        foreach (var наименование in new[] { "строки «От кого»", "строки «Откуда»" })
        {
            страница.Fields.Add(new BlankFieldSpec
            {
                Name = наименование,
                Kind = BlankFieldKinds.Text,
                Bounds = new BlankBounds { XMm = Отступ, YMm = yОтправителя, WidthMm = ширинаКолонки, HeightMm = ВысотаАдреса },
                WordWrap = true,
                MaxLines = 5,
                Printable = true,
            });
            yОтправителя += ВысотаАдреса + Зазор;
        }

        // Получатель — правая нижняя часть.
        var yПолучателя = высота - Отступ - (2 * (ВысотаАдреса + Зазор));
        var xПолучателя = ширина - Отступ - праваяКолонка;
        foreach (var наименование in new[] { "строки «Кому»", "строки «Куда»" })
        {
            страница.Fields.Add(new BlankFieldSpec
            {
                Name = наименование,
                Kind = BlankFieldKinds.Text,
                Bounds = new BlankBounds { XMm = xПолучателя, YMm = yПолучателя, WidthMm = праваяКолонка, HeightMm = ВысотаАдреса },
                WordWrap = true,
                MaxLines = 5,
                Printable = true,
            });
            yПолучателя += ВысотаАдреса + Зазор;
        }

        // Вспомогательные реквизиты — левая колонка ниже отправителя,
        // не заходя в нижнюю полосу индекса.
        var верхИндекса = высота - Отступ - ВысотаШтампа - Зазор;
        var y = yОтправителя + Зазор;
        foreach (var наименование in вспомогательные)
        {
            if (y + ВысотаСтроки > верхИндекса)
            {
                break;
            }

            страница.Fields.Add(new BlankFieldSpec
            {
                Name = наименование,
                Kind = BlankFieldKinds.Text,
                Bounds = new BlankBounds { XMm = Отступ, YMm = y, WidthMm = ширинаКолонки, HeightMm = ВысотаСтроки },
                WordWrap = true,
                MaxLines = 1,
                Printable = true,
            });
            y += ВысотаСтроки + Зазор;
        }

        // Кодовый штамп индекса получателя — левый нижний угол.
        ШтампыСлеваВПолосу(
            страница,
            new[] { ("Индекс для машинной обработки", true) },
            ширина,
            высота);
    }

    /// <summary>Адресные поля — многострочные, печатаются из данных письма.</summary>
    private static bool ЯвляетсяАдресным(string наименование) =>
        наименование.StartsWith("Строки", StringComparison.OrdinalIgnoreCase)
        || наименование.StartsWith("строки", StringComparison.OrdinalIgnoreCase);

    /// <summary>Курсор раскладки: продолжение после последнего текстового поля.</summary>
    private static (decimal X, decimal Y) НачальныйКурсор(BlankPage страница)
    {
        var текстовые = страница.Fields.Where(поле => поле.Kind == BlankFieldKinds.Text).ToList();

        if (текстовые.Count == 0)
        {
            return (Отступ, Отступ);
        }

        var последний = текстовые[^1];

        return (последний.Bounds.XMm, последний.Bounds.BottomMm + Зазор);
    }
}

/// <summary>
/// Восемь встроенных эталонных бланков с размерами в мм и фоновым рисунком
/// (ТЗ §8.3, функция 36: <c>Infrastructure.Templates.BuiltinTemplatesCatalog</c>).
/// </summary>
/// <remarks>
/// <para>Разметки собираются по словарю полей встроенных форм
/// (EVIDENCE/blank_field_vocabulary.txt); числа текстовых полей зафиксированы
/// заданием этапа: ф.112эп — 39, ф.112э — 39, ф.112эф — 81, ф.112эю — 81,
/// ф.117+ф.113 — 95, ф.116 — 83, ф.119 (2011) — 11 (2 страницы),
/// C5 (2012) — 46. Поля кодового штампа добавляются к текстовым.</para>
/// <para>Растровые подложки поставляются отдельным набором ассетов; имя файла
/// подложки сохраняется в разметке, и если файл найден в каталоге ассетов,
/// он включается в пакет .lbk.</para>
/// </remarks>
public sealed class BuiltinTemplatesCatalog
{
    /// <summary>Каталог ассетов подложек встроенных бланков; <see langword="null"/> — без ассетов.</summary>
    private readonly string? _каталогАссетов;

    /// <summary>Создаёт каталог встроенных бланков.</summary>
    /// <param name="assetsDirectory">Каталог растровых подложек; <see langword="null"/> — без ассетов.</param>
    public BuiltinTemplatesCatalog(string? assetsDirectory = null)
    {
        _каталогАссетов = assetsDirectory;
    }

    /// <summary>
    /// Возвращает встроенный бланк (ТЗ §8.3, функция 36:
    /// <c>GetBuiltinTemplate(BuiltinFormType form)</c>).
    /// </summary>
    /// <param name="form">Вид формы.</param>
    /// <returns>Модель бланка.</returns>
    public CustomBlank GetBuiltinTemplate(BuiltinFormType form) => form switch
    {
        BuiltinFormType.Form112ep => Форма112эп(),
        BuiltinFormType.Form112e => Форма112э(),
        BuiltinFormType.Form112ef => Форма112эф(),
        BuiltinFormType.Form112eyu => Форма112эю(),
        BuiltinFormType.Form117and113 => Форма117и113(),
        BuiltinFormType.Form116 => Форма116(),
        BuiltinFormType.Form119_2011 => Форма119(),
        BuiltinFormType.EnvelopeC5_2012 => КонвертC5(),
        _ => throw new ArgumentOutOfRangeException(nameof(form), form, "Неизвестный встроенный бланк."),
    };

    /// <summary>
    /// Полная библиотека встроенных шаблонов: 8 эталонных бланков плюс
    /// конверты, доверенности и служебные формы — не менее 20 пакетов
    /// (ТЗ §8.3, функция 37).
    /// </summary>
    /// <returns>Список пар «имя пакета — бланк».</returns>
    public IReadOnlyList<(string PackageName, CustomBlank Blank)> BuildLibrary()
    {
        var библиотека = new List<(string, CustomBlank)>();

        foreach (BuiltinFormType вид in Enum.GetValues<BuiltinFormType>())
        {
            библиотека.Add(("0000" + Наименование(вид), GetBuiltinTemplate(вид)));
        }

        // Конверты стандартной серии (ТЗ §8.3, ф.37: C4, C5, C6, DL, B4 и др.).
        foreach (var (код, ширина, высота) in new[]
                 {
                     ("C6", 162m, 114m),
                     ("DL", 220m, 110m),
                     ("C5", 229m, 162m),
                     ("C4", 324m, 229m),
                     ("C5/О", 229m, 162m),
                     ("DL/О", 220m, 110m),
                     ("B4", 353m, 250m),
                     ("E65", 220m, 110m),
                     ("K5", 215m, 145m),
                     ("K6", 125m, 125m),
                     ("K65", 190m, 125m),
                     ("C6/О", 162m, 114m),
                 })
        {
            библиотека.Add(("Конверт " + код, КонвертСерии(код, ширина, высота)));
        }

        // S25 (функция 144): расширенная серия ГОСТ Р 51506-99 / ISO —
        // реальные размеры конвертов, каждый макет строится КонвертСерии
        // с собственными штампами/QR, различим по коду и габаритам.
        foreach (var (код, ширина, высота) in new[]
                 {
                     ("C6/5", 114m, 229m),
                     ("B6", 125m, 176m),
                     ("C7/C6", 81m, 162m),
                     ("E1", 108m, 158m),
                     ("№10", 105m, 241m),
                     ("B5", 176m, 250m),
                 })
        {
            библиотека.Add(("Конверт " + код, КонвертСерии(код, ширина, высота)));
        }

        // S25: праздничные открытки — реальные макеты A6 с собственными
        // полями-поздравлениями (отличаются заголовком и набором полей).
        foreach (var название in new[]
                 {
                     "Поздравительная открытка «Цветы»",
                     "Поздравительная открытка «Ёлка»",
                     "Новогодняя открытка",
                     "Открыта к 8 Марта",
                     "Открытка к 23 Февраля",
                     "Открытка к Дню Победы",
                 })
        {
            var бланкОткрытки = Заготовка(название, 105m, 148m, 1);
            бланкОткрытки.Pages[0].Fields.Add(new BlankFieldSpec
            {
                Name = "Заголовок поздравления",
                Kind = BlankFieldKinds.Text,
                Bounds = new BlankBounds
                {
                    XMm = 10m,
                    YMm = 10m,
                    WidthMm = 85m,
                    HeightMm = 10m,
                },
                Printable = true,
            });
            бланкОткрытки.Pages[0].Fields.Add(new BlankFieldSpec
            {
                Name = "Текст поздравления",
                Kind = BlankFieldKinds.Text,
                Bounds = new BlankBounds
                {
                    XMm = 10m,
                    YMm = 24m,
                    WidthMm = 85m,
                    HeightMm = 40m,
                },
                Printable = true,
            });
            бланкОткрытки.Pages[0].Fields.Add(new BlankFieldSpec
            {
                Name = "Подпись отправителя",
                Kind = BlankFieldKinds.Text,
                Bounds = new BlankBounds
                {
                    XMm = 10m,
                    YMm = 68m,
                    WidthMm = 85m,
                    HeightMm = 10m,
                },
                Printable = true,
            });
            библиотека.Add(("Открытка «" + название + "»", бланкОткрытки));
        }

        // S25: офисные бланки — реальные макеты A4 с функциональными
        // наборами полей (не пустые заглушки).
        CustomBlank бланкМакет;
        foreach (var (название, поляФормы) in new[]
                 {
                     ((string Name, string[] Fields))("Официальное письмо (шапка)",
                         ["Организация", "Адрес", "Телефон", "Дата", "Номер", "Заголовок", "Текст письма", "Подпись"]),
                     ("Служебная записка",
                         ["Организация", "Кому", "От кого", "Дата", "Тема", "Текст записки", "Подпись"]),
                     ("Факс",
