    /// <summary>Возвращает байты файла подложки, если ассет найден.</summary>
    /// <param name="fileName">Имя файла из разметки.</param>
    /// <returns>Байты файла либо <see langword="null"/>.</returns>
    public byte[]? TryGetAsset(string? fileName)
    {
        if (_каталогАссетов is null || string.IsNullOrWhiteSpace(fileName))
        {
            return null;
        }

        var путь = Path.Combine(_каталогАссетов, fileName);

        return File.Exists(путь) ? File.ReadAllBytes(путь) : null;
    }

