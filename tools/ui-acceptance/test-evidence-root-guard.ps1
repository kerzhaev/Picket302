# Статический страж регрессии 2026-11-08: драйверы приёмки не должны
# писать evidence в каталог ПРЕДЫДУЩЕЙ серии и не должны оставлять
# жёстко заданный путь внутри репозитория.
#
# Дефект, который закрывает страж: run-emptybook.ps1 и run-printflow.ps1
# содержали жёстко заданный $out = '...\docs\ux-audit-2026-11-03\
# после-этапа-редизайна'. Прогон драйвера ПЕРЕЗАПИСЫВАЛ скриншоты прошлой
# серии (01-адресная-книга-пустая-1280x720.png отслеживается git!) и
# добавлял новые файлы в отслеживаемый каталог — прямое нарушение правила
# «не перезаписывай старые evidence-файлы другой серией» и требования
# чистоты рабочего каталога.
#
# Контракт стража:
#   1. каждый run-*.ps1 берёт каталог evidence из P302_EVIDENCE_ROOT либо
#      из подкаталога с датой текущей серии;
#   2. ни один run-*.ps1 не содержит литерала 'ux-audit-2026-11-03'
#      и прочих каталогов прошлых серий;
#   3. harness (Program.cs) не содержит жёстко заданных путей evidence.
#
# Exit 0 — страж пройден; exit 1 — нарушение найдено (fail-closed).

$ErrorActionPreference = 'Stop'

$каталог = $PSScriptRoot
$драйверы = @(Get-ChildItem -Path $каталог -Filter 'run-*.ps1' -File)

if ($драйверы.Count -eq 0) {
    Write-Host 'GUARD FAIL: драйверы run-*.ps1 не найдены'
    exit 1
}

$нарушения = [System.Collections.Generic.List[string]]::new()
$проверено = 0

foreach ($драйвер in $драйверы) {
    $проверено++

    $текст = [System.IO.File]::ReadAllText($драйвер.FullName, [System.Text.Encoding]::UTF8)

    # (1) Драйвер, который ПИШЕТ evidence (файл отчёта или скриншот),
    # обязан получать каталог из P302_EVIDENCE_ROOT (напрямую или через
    # общий помощник Get-EvidenceRoot из acceptance-lib.ps1).
    $пишетEvidence = $текст -match 'ЗаписатьEvidence|\[AccWin\]::Capture'
    $используетКорень = $текст -match 'P302_EVIDENCE_ROOT|Get-EvidenceRoot'

    if ($пишетEvidence -and -not $используетКорень) {
        $нарушения.Add("$($драйвер.Name): пишет evidence, но не использует P302_EVIDENCE_ROOT/Get-EvidenceRoot")
    }

    # (2) Запрещённые литералы прошлых серий.
    foreach ($запрещённый in @('ux-audit-2026-11-03', 'после-этапа-редизайна', 'после-исправлений')) {
        if ($текст.Contains($запрещённый)) {
            # Допускается только упоминание в комментарии, объясняющем
            # регрессию; проверяем, что это именно комментарий, а не
            # присваиваемое значение.
            foreach ($строка in ($текст -split "`r?`n")) {
                if ($строка.Contains($запрещённый) -and $строка -notmatch '^\s*#') {
                    $нарушения.Add("$($драйвер.Name): литерал '$запрещённый' в исполняемой строке: $($строка.Trim())")
                }
            }
        }
    }
}

# (3) harness не должен содержать жёстко заданных путей evidence.
$program = Join-Path $каталог 'Program.cs'

if (Test-Path $program) {
    $проверено++
    $текстПрограммы = [System.IO.File]::ReadAllText($program, [System.Text.Encoding]::UTF8)

    if ($текстПрограммы -match 'ux-audit-2026-11-03|после-этапа-редизайна') {
        $нарушения.Add('Program.cs: содержит жёстко заданный путь evidence прошлой серии')
    }
}

Write-Host "GUARD: проверено файлов: $проверено"

if ($нарушения.Count -gt 0) {
    Write-Host "GUARD FAIL: нарушений $($нарушения.Count)"

    foreach ($нарушение in $нарушения) {
        Write-Host "  - $нарушение"
    }

    exit 1
}

Write-Host 'GUARD PASS: драйверы приёмки не пишут в каталоги прошлых серий'
exit 0
